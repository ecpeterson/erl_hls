-module(xls_statem_identity_tests).
-moduledoc "Checks canonical compiler build identities, retained source semantics and exact generated bytes across relocation; these are metadata regressions, not equivalence proofs.".
-include_lib("eunit/include/eunit.hrl").

-define(GATHER, "test_data/xls_statem_gather_fixture.erl").
-define(ENTRY, "test/xls_entry_outcome_fixture.erl").

%% Fresh origins may differ, but their sharing relation must remain observable.
-spec fresh_compilation_and_alias_identity_test() -> ok.
fresh_compilation_and_alias_identity_test() ->
    {_, First} = xls_statem_plan:from_file(?ENTRY, []),
    {_, Second} = xls_statem_plan:from_file(?ENTRY, []),
    Expected = xls_statem_plan:identity(First),
    ?assertNotEqual(First, Second),
    ?assertEqual(Expected, xls_statem_plan:identity(Second)),
    ?assertEqual(Expected, xls_statem_plan:identity(binary_to_term(term_to_binary(First)))),
    ?assertEqual([artifact_sha256, plan_sha256, planner_md5, source_sha256, version],
        lists:sort(maps:keys(Expected))),
    #{version := 1, planner_md5 := Md5} = Expected,
    ?assertEqual(32, byte_size(Md5)),
    lists:foreach(fun(Key) -> ?assertEqual(64, byte_size(maps:get(Key, Expected))) end,
        [source_sha256, artifact_sha256, plan_sha256]),
    lists:foreach(fun(Changed) ->
        Identity = xls_statem_plan:identity(Changed),
        ?assertNotEqual(maps:get(plan_sha256, Expected), maps:get(plan_sha256, Identity)),
        ?assertEqual(maps:get(source_sha256, Expected), maps:get(source_sha256, Identity)),
        ?assertEqual(maps:get(artifact_sha256, Expected), maps:get(artifact_sha256, Identity))
    end, [origins(First, split), origins(First, make_ref()), First#{callbacks := []}]).

%% Source outside callback dispatch still participates in the source identity.
-spec complete_source_is_bound_test() -> ok.
complete_source_is_bound_test() ->
    {ok, Forms} = xls_parse:parse_file(?GATHER, []),
    {_, Before} = planned(Forms),
    {_, After} = planned(Forms ++ [form("host_only() -> 42.")]),
    A = xls_statem_plan:identity(Before), B = xls_statem_plan:identity(After),
    ?assertNotEqual(maps:get(source_sha256, A), maps:get(source_sha256, B)),
    ?assertEqual(maps:get(callbacks, xls_statem_plan:manifest(Before)),
        maps:get(callbacks, xls_statem_plan:manifest(After))).

%% Relocated contexts use isolated preprocessing peers, so allow their startup time.
-spec relocation_and_preprocessing_test_() -> {timeout, pos_integer(), fun(() -> ok)}.
relocation_and_preprocessing_test_() -> {timeout, 60, fun relocation_and_preprocessing/0}.

%% Bind preprocessing inputs even when an option is unused by the emitted actor.
-spec relocation_and_preprocessing() -> ok.
relocation_and_preprocessing() ->
    with_roots(fun(A, B, Original) ->
        Body = binary:replace(Original, <<"* 1000.">>, <<"* ?LAST_WEIGHT.">>),
        Source = ["-include(\"value.hrl\").\n", Body],
        lists:foreach(fun(Root) ->
            ok = file:write_file(source(Root), Source),
            ok = file:write_file(header(Root), "-define(LAST_WEIGHT, 1000).\n")
        end, [A, B]),
        {SpecA, PlanA} = compile(A, context(A)),
        {SpecB, PlanB} = compile(B, context(B)),
        Identity = xls_statem_plan:identity(PlanA),
        ?assertEqual(Identity, xls_statem_plan:identity(PlanB)),
        ?assertEqual(render(SpecA), render(SpecB)),
        %% Absolute provenance is still retained and strict freshness is separate.
        ?assertNotEqual(maps:get(source_sha256, xls_statem_plan:manifest(PlanA)),
            maps:get(source_sha256, xls_statem_plan:manifest(PlanB))),
        ?assertError(stale_statem_plan, xls_statem_plan:validate(source(B), context(B), PlanA)),
        C = context(A),
        Variants = [C#{macros := [{'UNUSED', 1}]},
            C#{macros := [{'UNUSED', 2}]},
            C#{macros := [{'LEFT', 1}, {'RIGHT', 2}]},
            C#{macros := [{'RIGHT', 2}, {'LEFT', 1}]},
            C#{includes := ["unused", "include"]}],
        VariantIdentities = [begin
            {Spec, Plan} = compile(A, Variant),
            ?assertEqual(render(SpecA), render(Spec)),
            Id = xls_statem_plan:identity(Plan),
            ?assertNotEqual(maps:get(source_sha256, Identity), maps:get(source_sha256, Id)),
            Id
        end || Variant <- Variants],
        ?assertEqual(length(Variants), length(lists:usort(VariantIdentities))),
        ok = file:write_file(header(A), "-define(LAST_WEIGHT, 1001).\n"),
        {ChangedSpec, ChangedPlan} = compile(A, C),
        Changed = xls_statem_plan:identity(ChangedPlan),
        ?assertNotEqual(maps:get(source_sha256, Identity), maps:get(source_sha256, Changed)),
        ?assertNotEqual(maps:get(artifact_sha256, Identity), maps:get(artifact_sha256, Changed)),
        ?assertNotEqual(render(SpecA), render(ChangedSpec))
    end).

%% Moving one actor under the same build context also preserves its logical name.
-spec source_spelling_and_directory_test() -> ok.
source_spelling_and_directory_test() ->
    with_roots(fun(A, B, Original) ->
        ok = file:write_file(source(A), Original),
        ok = file:write_file(source(B), Original),
        {ok, Cwd} = file:get_cwd(),
        Relative = filename:join(["_build", filename:basename(filename:dirname(A)),
            "a", "src", "actor.erl"]),
        {SpecA, PlanA} = xls_statem_plan:from_file(Relative, []),
        {SpecB, PlanB} = xls_statem_plan:from_file(source(B), []),
        {SpecAbsolute, PlanAbsolute} = xls_statem_plan:from_file(filename:absname(Relative, Cwd), []),
        ?assertEqual(xls_statem_plan:identity(PlanA), xls_statem_plan:identity(PlanB)),
        ?assertEqual(xls_statem_plan:identity(PlanA), xls_statem_plan:identity(PlanAbsolute)),
        ?assertEqual(render(SpecA), render(SpecB)),
        ?assertEqual(render(SpecA), render(SpecAbsolute))
    end).

%% A location used by source preprocessing is semantic, unlike diagnostic metadata.
-spec semantic_file_expansion_test_() -> {timeout, pos_integer(), fun(() -> ok)}.
semantic_file_expansion_test_() -> {timeout, 60, fun semantic_file_expansion/0}.

%% Identical source bytes deliberately select different arithmetic through ?FILE.
-spec semantic_file_expansion() -> ok.
semantic_file_expansion() ->
    with_roots(fun(A, B, Original) ->
        Prefix = io_lib:format("-if(?FILE =:= ~p).\n-define(FILE_WEIGHT, 1000).\n"
            "-else.\n-define(FILE_WEIGHT, 1001).\n-endif.\n", [source(A)]),
        Body = binary:replace(Original, <<"* 1000.">>, <<"* ?FILE_WEIGHT.">>),
        lists:foreach(fun(Root) -> ok = file:write_file(source(Root), [Prefix, Body]) end, [A, B]),
        {SpecA, PlanA} = compile(A, context(A)),
        {SpecB, PlanB} = compile(B, context(B)),
        ?assertNotEqual(xls_statem_plan:identity(PlanA), xls_statem_plan:identity(PlanB)),
        ?assertNotEqual(render(SpecA), render(SpecB))
    end).

%% All fixture files are private to this test and are removed even on assertion failure.
-spec with_roots(fun((file:filename(), file:filename(), binary()) -> ok)) -> ok.
with_roots(Fun) ->
    Top = filename:absname(filename:join("_build", "statem-identity-" ++
        integer_to_list(erlang:unique_integer([positive])))),
    A = filename:join(Top, "a"), B = filename:join(Top, "b"),
    {ok, Original} = file:read_file(?GATHER),
    lists:foreach(fun(Root) ->
        ok = filelib:ensure_dir(source(Root)),
        ok = filelib:ensure_dir(header(Root)),
        ok = filelib:ensure_dir(filename:join([Root, "unused", "placeholder"]))
    end, [A, B]),
    try Fun(A, B, Original)
    after ok = file:del_dir_r(Top)
    end.

%% Use a source-relative include tree and explicitly captured preprocessing root.
-spec context(file:filename()) -> hls_source:context().
context(Root) -> #{directory => Root, source_name => source(Root),
    includes => ["include", "unused"], macros => [], features => []}.

%% Keep the actor basename fixed while changing only its enclosing build root.
-spec source(file:filename()) -> file:filename().
source(Root) -> filename:join([Root, "src", "actor.erl"]).

%% Header topology is part of source identity, not just the header basename.
-spec header(file:filename()) -> file:filename().
header(Root) -> filename:join([Root, "include", "value.hrl"]).

%% Exercise the public compiler entry point rather than constructing a plan fixture.
-spec compile(file:filename(), hls_source:context()) ->
    {xls_actor_codegen:spec(), xls_statem_plan:plan()}.
compile(Root, Context) -> xls_statem_plan:from_file(source(Root), Context).

%% Compare exact output bytes independently of canonical identity projection.
-spec render(xls_actor_codegen:spec()) -> binary().
render(Spec) -> iolist_to_binary(xls_statem_codegen:emit(Spec)).

%% Split every occurrence, or merge all occurrences, without editing other structure.
-spec origins(term(), split | reference()) -> term().
origins(Ref, split) when is_reference(Ref) -> make_ref();
origins(Ref, Replacement) when is_reference(Ref) -> Replacement;
origins(Map, Mode) when is_map(Map) -> maps:map(fun(_, Value) -> origins(Value, Mode) end, Map);
origins(Tuple, Mode) when is_tuple(Tuple) -> list_to_tuple([origins(X, Mode) || X <- tuple_to_list(Tuple)]);
origins(List, Mode) when is_list(List) -> [origins(X, Mode) || X <- List];
origins(Value, _Mode) -> Value.

%% Compile an extended source list through ordinary preparation and closure checks.
-spec planned([hls_source:form()]) -> {xls_actor_codegen:spec(), xls_statem_plan:plan()}.
planned(Forms) ->
    xls_statem_lower:planned_artifact(?GATHER, Forms, xls_parse:find_attribute(Forms, hls_phases)).

%% Parse a small declaration so its source fingerprint uses the actual Erlang AST.
-spec form(string()) -> hls_source:form().
form(Text) ->
    {ok, Tokens, _} = erl_scan:string(Text),
    {ok, Form} = erl_parse:parse_form(Tokens),
    Form.
