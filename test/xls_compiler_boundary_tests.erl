-module(xls_compiler_boundary_tests).
-moduledoc "Checks compiler entrypoints and source-query ownership; generated services are compilation regressions, not hardware witnesses.".
-include_lib("eunit/include/eunit.hrl").

%% Internal lowering operations belong to their owning passes, not the facade.
-spec public_entrypoints_test() -> ok.
public_entrypoints_test() ->
    Expected = [{actor_artifact, 2}, {actor_artifact, 3},
        {actor_interface, 1}, {actor_interface, 2}, {actor_interface, 3},
        {to_artifact, 1}, {to_artifact, 2}, {to_xls, 1}, {to_xls, 2},
        {module_info, 0}, {module_info, 1}],
    ?assertEqual(lists:sort(Expected), lists:sort(xls_parse:module_info(exports))).

%% Source inspection and record analysis must remain usable without a backend dependency.
-spec source_query_dependencies_test() -> ok.
source_query_dependencies_test() ->
    lists:foreach(fun(Module) ->
        Dependencies = source_dependencies(Module),
        ?assertEqual({Module, []}, {Module, [M || M <- Dependencies,
            lists:prefix("xls_", atom_to_list(M))]})
    end, [hls_source, hls_records, hls_actor_source]),
    lists:foreach(fun(Module) ->
        Dependencies = source_dependencies(Module),
        ?assertEqual({Module, []}, {Module, [M || M <- Dependencies,
            M =:= xls_parse orelse M =:= xls_clause_lower]})
    end, [hls_pack, hls_service_contract]).

%% Inspect parsed calls and remote funs, so comments or generated DSLX strings cannot mask dependencies.
-spec dependency_scanner_test() -> ok.
dependency_scanner_test() ->
    {ok, Tokens, _} = erl_scan:string(
        "sample() -> xls_clause_lower:print([]), fun xls_parse:to_xls/1."),
    {ok, Form} = erl_parse:parse_form(Tokens),
    ?assertEqual([xls_clause_lower, xls_parse], lists:usort(remote_modules(Form))),
    ?assertEqual([], remote_modules({string, 1, "xls_parse:to_xls"})).

%% Fresh source preparation may start an isolated preprocessing peer.
-spec normal_compilation_test_() -> {timeout, pos_integer(), fun(() -> ok)}.
normal_compilation_test_() -> {timeout, 60, fun normal_compilation/0}.

%% Each public dispatch path retains its distinct service model and state vocabulary.
-spec normal_compilation() -> ok.
normal_compilation() ->
    Immediate = iolist_to_binary(xls_parse:to_xls("test/xls_init_gs_fixture.erl")),
    ?assertEqual(Immediate, xls_emitted:bytes(xls_parse:to_artifact("test/xls_init_gs_fixture.erl"))),
    contains(Immediate, [
        <<"// test/xls_init_gs_fixture.erl.x\n">>,
        <<"// This file is auto-generated by xls_parse. Manual changes will be over-">>,
        <<"proc Service {">>, <<"proc Top {">>, <<"struct Ledger {">>
    ]),
    ?assertEqual(nomatch, binary:match(Immediate, <<"hls_server::Driver">>)),
    Deferred = iolist_to_binary(xls_parse:to_xls("test/hls_deferred_fixture.erl", #{})),
    contains(Deferred, [<<"hls_server::Driver">>, <<"fn reply_allowed(">>, <<"pub proc Top {">>]),
    File = "test/hls_statem_event_fixture.erl",
    Machine = iolist_to_binary(xls_parse:to_xls(File, #{})),
    contains(Machine, [<<"enum Phase : u8 {">>, <<"next_event: u8">>]),
    Artifact = xls_parse:actor_artifact(File, []),
    ?assertMatch(#{phases := [waiting, sending], data_name := cell,
        continuations := [drain], retained_calls := none}, Artifact),
    ?assertEqual(xls_parse:actor_interface(File), xls_parse:actor_interface(File, [])),
    ok.

%% Required service declarations check routing without depending on whole-file formatting.
-spec contains(binary(), [binary()]) -> ok.
contains(Source, Needles) ->
    lists:foreach(fun(Needle) ->
        ?assertNotEqual({Needle, nomatch}, {Needle, binary:match(Source, Needle)})
    end, Needles).

%% Preprocess source only; compiler parse transforms are intentionally not executed here.
-spec source_dependencies(module()) -> [module()].
source_dependencies(Module) ->
    Path = filename:join("src/frontend", atom_to_list(Module) ++ ".erl"),
    {ok, Forms} = epp:parse_file(Path, [], []),
    ?assertEqual([], [Error || Error = {error, _} <- Forms]),
    lists:usort(remote_modules(Forms)).

%% Both remote calls and captured remote functions introduce a module dependency.
-spec remote_modules(term()) -> [module()].
remote_modules({remote, _, {atom, _, Module}, _}) -> [Module];
remote_modules({'fun', _, {function, {atom, _, Module}, _, _}}) -> [Module];
remote_modules(Term) when is_tuple(Term) -> remote_modules(tuple_to_list(Term));
remote_modules(Terms) when is_list(Terms) -> lists:append([remote_modules(Term) || Term <- Terms]);
remote_modules(_) -> [].
