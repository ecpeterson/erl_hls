%% The published fixtures were generated by the pinned independent Python decoder.
-spec fixtures() -> {[map()], [map()]}.
fixtures() ->
    {ok, Bytes} = file:read_file(filename:join([code:priv_dir(hls_snowflake), "fixtures", "surface-named.json"])),
    #{<<"cases">> := Cases, <<"geometries">> := Geometries} = json:decode(Bytes),
    {Cases, Geometries}.

%% Geometry-addressed field comparison avoids assuming identical storage order.
-spec check_fixture(map(), [map()], map()) -> ok.
check_fixture(#{<<"distance">> := Distance, <<"window_height">> := Height,
        <<"sheets">> := Sheets}, Geometries, Options) ->
    [Geometry] = [G || G = #{<<"distance">> := D, <<"window_height">> := H} <- Geometries,
        D =:= Distance, H =:= Height],
    Actual = snowflake_actor_run:run(Distance, Height,
        [maps:get(<<"input_mask">>, Sheet) || Sheet <- Sheets], Options),
    lists:foreach(fun({Expected, Report}) ->
        lists:foreach(fun(Field) ->
            ?assertEqual(maps:get(atom_to_binary(Field), Expected), maps:get(Field, Report))
        end, [retired_sheet, retired_spatial_mask, retired_temporal_mask]),
        ?assertEqual(maps:get(<<"reference_runtime_all">>, Expected) + 1, maps:get(ticks, Report)),
        case maps:find(<<"state">>, Expected) of
            {ok, ExpectedState} -> ?assertEqual(ExpectedState, reference_state(maps:get(state, Report), Geometry));
            error -> ok
        end
    end, lists:zip(Sheets, Actual)).

%% The reference serializes Boolean fields as bits and names vertices independently.
-spec reference_state(map(), map()) -> map().
reference_state(#{nodes := Nodes, edges := Edges}, #{<<"nodes">> := NodeGeometry,
        <<"edges">> := EdgeGeometry}) ->
    NodeMap = maps:from_list([{maps:get(coordinate, N), N} || N <- Nodes]),
    EdgeMap = maps:from_list([{maps:get(endpoints, E), E} || E <- Edges]),
    Fields = [active, whole, cid, defect, pointer, grown, unrooted, busy],
    #{<<"nodes">> => [[numeric(maps:get(Field, maps:get(Coordinate, NodeMap))) || Field <- Fields]
        || #{<<"coordinate">> := Coordinate} <- NodeGeometry],
      <<"edges">> => [[numeric(maps:get(Field, maps:get(Endpoints, EdgeMap)))
        || Field <- [growth, correction]] || Endpoints <- EdgeGeometry]}.

%% Signed identifiers remain integers; Boolean values become fixture bits.
-spec numeric(boolean() | integer()) -> integer().
numeric(false) -> 0;
numeric(true) -> 1;
numeric(Value) -> Value.
