%% Delaying one source's snapshots/status changes arrival order without scheduling phases in the driver.
-spec delayed_neighbor_test_() -> term().
delayed_neighbor_test_() ->
    {timeout, 5, fun() ->
        {Cases, Geometries} = fixtures(),
        [Case] = [C || C = #{<<"name">> := <<"surface_d3_burst">>} <- Cases],
        check_fixture(Case, Geometries, #{delay_source => {vertex, 0}, delay_ms => 1})
    end}.

%% Eight in-flight sheets cannot starve the coordinator's acknowledgment mailbox.
-spec credited_burst_test_() -> term().
credited_burst_test_() ->
    {timeout, 5, fun() ->
