-module(snowflake_actor_tests).
-moduledoc "Geometry, stream and pinned-reference checks for communicating Snowflake actors.".
-include_lib("eunit/include/eunit.hrl").
-include("snowflake_actor_protocol.hrl").

%% Correction ownership partitions retired edges, including bottom-to-next temporal edges.
-spec geometry_test() -> ok.
geometry_test() ->
    Geometry = snowflake_actor_topology:geometry(3, 3),
    #{coordinates := Coordinates, retired_spatial := Spatial, retired_temporal := Temporal} = Geometry,
    ?assertEqual(36, tuple_size(Coordinates)),
    Owners = snowflake_actor_topology:ownership(Geometry),
    ?assertEqual(lists:sort([E - 1 || E <- tuple_to_list(Spatial) ++ tuple_to_list(Temporal)]),
        lists:sort([maps:get(edge, Owner) || Owner <- Owners])),
    ?assertEqual(19, length(Owners)),
    ?assertEqual([4], lists:usort([maps:get(direction, Owner) || Owner = #{kind := temporal} <- Owners])),
    Configs = [snowflake_actor_topology:vertex_config(I, Geometry) || I <- lists:seq(0, 35)],
    ?assertEqual(lists:seq(0, 5), lists:sort([Bit || #sf_vertex_config{syndrome_bit = Bit} <- Configs, Bit =/= 255])),
    ?assertEqual(24, length([ok || #sf_vertex_config{below = true} <- Configs])),
    ?assertEqual(12, length([ok || #sf_vertex_config{top = true} <- Configs])),
    ?assertEqual(12, length([ok || #sf_vertex_config{bottom = true} <- Configs])),
    ?assertEqual(150, tuple_size(maps:get(coordinates, snowflake_actor_topology:geometry(5, 5)))),
    ?assertError({actor_protocol_capacity, {392, 42}}, snowflake_actor_topology:geometry(7, 7)).

%% Boundary temporal shifts exist even where the decoder graph has no temporal edge.
-spec boundary_shift_route_test() -> ok.
boundary_shift_route_test() ->
    #{routes := Routes} = snowflake_actor_topology:topology(),
    ?assertEqual([{{{vertex, 1}, below}, [{actor, {vertex, 0}}]}],
        [Route || Route = {{{vertex, 1}, below}, _} <- Routes]),
    ?assertEqual([{{{vertex, 1}, down}, [{external, unexpected}]}],
        [Route || Route = {{{vertex, 1}, down}, _} <- Routes]).

%% Quiet, boundary, temporal, burst and sustained noisy streams retain every reference state.
-spec reference_streams_test_() -> term().
reference_streams_test_() ->
    {timeout, 15, fun() ->
        {Cases, Geometries} = fixtures(),
        lists:foreach(fun(Case) -> check_fixture(Case, Geometries, #{}) end, Cases)
    end}.

%% Exhaust all pinned three-sheet single-fault D3 streams without adding drain inputs.
-spec enumerated_streams_test_() -> term().
enumerated_streams_test_() ->
    {timeout, 15, fun() ->
