-module(xls_protocol_envelope).
-moduledoc "Renders DSLX declarations and codecs for the runtime-owned packet and rectangle schemas. The checked support-source generator reads hls_protocol_envelope fields so handwritten runtime packing and generated hardware do not maintain independent wire layouts.".

%% Canonical envelope support emission.
-export([emit/0]).

-doc "Returns the fixed Packet and RectangleCommand DSLX structs and codecs without writing files. The checked-in protocol_envelope.x is generated from these schemas; encoding is numeric low-field-first and introduces no hls_bits dependency.".
-spec emit() -> iodata().
emit() ->
    [
        "// Generated by xls_protocol_envelope:emit/0. Fixed transport wire layouts.\n\n",
        codec(packet, "Packet"),
        "\n",
        codec(rectangle, "RectangleCommand")
    ].

%% Generic struct codecs own all offsets and casts; the schema owns only ordered field types.
-spec codec(packet | rectangle, string()) -> iodata().
codec(Name, TypeName) ->
    Layout = xls_struct_codec:layout(hls_protocol_envelope:fields(Name), lsb),
    Suffix = atom_to_list(Name),
    [
        "// Ordered wire fields; semantic validation belongs to the transport owner.\n",
        xls_struct_codec:declaration(TypeName, Layout),
        "// Decode the complete fixed-width wire envelope.\n",
        xls_struct_codec:decoder(TypeName, "unpack_" ++ Suffix, Layout),
        "// Encode the complete fixed-width wire envelope.\n",
        xls_struct_codec:encoder(TypeName, "pack_" ++ Suffix, Layout)
    ].
