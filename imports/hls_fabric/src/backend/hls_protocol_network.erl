-module(hls_protocol_network).
-moduledoc "Connects ordinary DSLX owners and source-bound transport with declared startup messages. Host commands enter ordinary inbox slots; application admission remains separate.".
-export([plan/2, descriptor/1, phases/1, transport/1, write/2, write/3, emit/1, emit/2]).
-export_type([plan/0, options/0, activation/0, descriptor/0, manifest/0, result/0, output/0]).

-doc "Whether source captures run automatically after reset or wait for the ordered start handshake.".
-type activation() :: hls_source_config:activation().

-doc "Network-only configuration; omitted activation and inspection select automatic and none.".
-type options() :: hls_source_config:network_options().

-doc "The checked network interface before generated bytes and process-inspection evidence exist.".
-type descriptor() :: xls_protocol_network:descriptor().

-doc "The final network interface, including required generated-byte hashes and optional inspection evidence.".
-type manifest() :: xls_protocol_network:manifest().

-doc "Network files paired with their concrete final network/transport result.".
-type output() :: hls_generated_files:output(result()).

%% Retain the checked transport and its composition layout as one emission input.
-record(plan, {transport :: hls_protocol_transport:build(), layout :: xls_protocol_network:plan()}).

-doc "A checked network composition from plan/2. Retain unchanged in process; this is not a saved-plan input or hardware admission.".
-opaque plan() :: #plan{}.

-doc "The emitted network manifest and its finalized transport descriptor. Consumers retain the descriptor in memory rather than reading transport.etf back.".
-type result() :: #{network := manifest(), transport := hls_protocol_transport:descriptor()}.

-doc "Builds a sampled-clock DSLX network from hls_protocol_transport's trusted fresh-source config. Connects ordinary owners, whole entry batches, captures, declared startup and optional rectangle host input. Host commands retire only on source consume; malformed accepted commands fault until reset. Optional activation => explicit_start holds internal receives until a registered start handshake. Startup and host setup continue while stopped; start requires their consumption, no offered host command and no observed fault. Setup requiring internal feedback belongs after start. automatic is the default. inspection => process exposes a passive addressed metadata port; none is the default. native_actors selects a nonempty proper subset and exposes canonical raw crossing ports, retaining global identities. These require common clock/reset, ordered lossless delivery and stable offers until handshake; no framed network or independent reset protocol is supplied. Process inspection with a partition is currently rejected. arithmetic_groups selects disjoint source-compatible native scalar-completion groups through the fresh transport builder; omitted groups keep local completion. Each group has one combinational source callback and a round-robin cursor, feeding the existing registered owner action. External streams have no cross-source order. An unchanged composition plan may also be written directly. Returns an executable manifest with capacity/progress eligibility false. Requires a fresh directory. Generation failures create no output; I/O failures retain partial output.".
-spec write(hls_source_config:network() | file:filename() | plan(), file:filename()) -> manifest().
write(Config, Directory) ->
    #{network := Network} = hls_generated_files:write(emit(Config), Directory),
    Network.

-doc "Writes emit/2's planned network to a fresh directory and returns its named network/transport result. Generation precedes output creation; I/O failures retain partial output.".
-spec write(hls_protocol_transport:build(), options(), file:filename()) -> result().
write(Build, Options, Directory) ->
    hls_generated_files:write(emit(Build, Options), Directory).

-doc "Generates a network bundle without writing output. Accepts a trusted source config map or a filename containing one map; source paths remain relative to the caller. Preparation loads sources and invokes their trusted constructors. An unchanged plan/2 value skips preparation and layout checks. Returns relative filenames with IO data and named network/transport descriptors.".
-spec emit(hls_source_config:network() | file:filename() | plan()) -> output().
emit(#plan{transport = Build, layout = Layout}) ->
    #{files := TransportFiles, result := Transport} = hls_protocol_transport:emit(Build),
    #{files := NetworkFiles, result := Network} = xls_protocol_network:emit(Layout, TransportFiles),
    #{files => hls_generated_files:merge([TransportFiles, NetworkFiles]),
      result => #{transport => Transport, network => Network}};
emit(Config) when is_map(Config) ->
    Options = #{inspection := Inspection} = modes(maps:with([activation, inspection], Config)),
    ok = inspection(maps:is_key(native_actors, Config), Inspection),
    emit(hls_protocol_transport:plan(Config), Options);
emit(Filename) -> emit(hls_source_config:read(Filename)).

-doc "Checks network wiring and packed ports for an unchanged transport build. Options accepts activation and inspection only. Rejects unsupported modes, partition inspection and inconsistent receiver/link spans before rendering transport or composition hardware. Does not read templates or emit observation artifacts; the transport build retains checked source snapshots and receiver layouts.".
-spec plan(hls_protocol_transport:build(), options()) -> plan().
plan(Build, Options) ->
    Modes = #{inspection := Inspection} = modes(Options),
    Transport = #{fabric := Fabric} = hls_protocol_transport:descriptor(Build),
    ok = inspection(maps:is_key(crossings, Fabric), Inspection),
    #plan{transport = Build, layout = xls_protocol_network:plan(maps:merge(Transport, Modes))}.

-doc "Returns the checked static network interface, including ports, endpoints, state costs and inspection mode (none or process). It contains no generated-byte hashes or inspection catalog; emit/1 adds those to its final manifest. Treat this descriptor as read-only.".
-spec descriptor(plan()) -> descriptor().
descriptor(#plan{layout = Layout}) -> xls_protocol_network:descriptor(Layout).

-doc "Returns retained observe, preview, select, advance and commit wiring without source compilation or rendering. Includes native actor/grant identities, receiver-owned slices, sparse global host retirements and activation fault origins. These diagnostic facts are not executable plan input.".
-spec phases(plan()) -> xls_protocol_network:phases().
phases(#plan{layout = Layout}) -> xls_protocol_network:phases(Layout).

-doc "Returns the retained transport placement for source, topology and receiver-layout inspection. Reuses the checked snapshot without recompiling or rendering; retain it unchanged.".
-spec transport(plan()) -> hls_protocol_transport:build().
transport(#plan{transport = Build}) -> Build.

-doc "Plans and emits a connected network from an unchanged transport build. Options accepts activation/inspection only. Equivalent to emit(plan(Build, Options)); returns relative files and final network/transport descriptors. Template reads occur only after composition checks.".
-spec emit(hls_protocol_transport:build(), options()) -> output().
emit(Build, Options) -> emit(plan(Build, Options)).

%% Check configuration before source work, then check the actual cut at the emission boundary.
-spec inspection(boolean(), none | process) -> ok.
inspection(true, process) -> hls_diagnostic:raise(network, partition_inspection_unavailable,
    <<"Process inspection is unavailable for a native partition; select inspection => none.">>,
    #{path => [inspection], value => process, capability => partition_inspection});
inspection(_, _) -> ok.

%% Reject renderer options that could imply changing the already planned source or placement.
-spec modes(options()) -> #{activation := activation(), inspection := none | process}.
modes(Options) ->
    case maps:keys(maps:without([activation, inspection], Options)) of
        [] -> ok;
        Unknown -> hls_diagnostic:raise(network, unsupported_network_options,
            <<"Network composition accepts activation and inspection options only.">>,
            #{options => lists:sort(Unknown)})
    end,
    #{activation => activation(maps:get(activation, Options, automatic)),
      inspection => inspection_mode(maps:get(inspection, Options, none))}.

%% Reject unknown modes before reading sources or creating a partial output tree.
-spec activation(term()) -> activation().
activation(automatic) -> automatic;
activation(explicit_start) -> explicit_start;
activation(Other) -> hls_diagnostic:raise(network, unsupported_protocol_activation,
    <<"Activation must be automatic or explicit_start.">>, #{path => [activation], value => Other}).

%% Validate the public mode before rendering any observation hardware.
-spec inspection_mode(term()) -> none | process.
inspection_mode(none) -> none;
inspection_mode(process) -> process;
inspection_mode(Other) -> hls_diagnostic:raise(network, unsupported_protocol_inspection,
    <<"Inspection must be none or process.">>, #{path => [inspection], value => Other}).
