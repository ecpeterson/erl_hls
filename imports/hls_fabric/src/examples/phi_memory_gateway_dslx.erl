%%%% phi_memory_gateway_dslx
%%%%
%%%% Routed AXI-stream boundary for the phi memory experiment.

-module(phi_memory_gateway_dslx).
-moduledoc """
Generates the routed AXI-stream gateway around one phi/noise topology.

The checked artifact imports the distance-three topology. `to_dslx/1` also
emits the staging-only distance-one wrapper without flattening either imported
topology into the gateway source.

This generator renders only phi-specific boundary policy and composition.
Endpoint allocation, external order, message selectors, payload widths, target
selectors, and frame capacity come from `phi_memory_boundary`. Reusable routed
packet ingress, activation gating, and frame transmission live in
`hls_fabric_router.x`.

The generated gateway stops at a `RoutedFrame` stream. The physical wrapper
compiles the reusable host-bound serializer independently, allowing scheduler
RAM latency and AXI-stream beat rate to have different initiation intervals.

Malformed routes and frames are drained without actor delivery. Until the
gateway has a typed connection-fault sideband, the host observes that rejection
through the experiment timeout rather than an invented application reply.

Staging tools and gateway tests call this generator alongside phi_shared_noise_topology_dslx and phi_memory_debug_top_v. Logical actor codecs and phi_memory_boundary come from the compiler example library.
""".

%% Example routed gateway generation.
-export([to_dslx/0, to_dslx/1, to_dslx/2, to_dslx/3]).

-doc "Generates the checked distance-three gateway.".
-spec to_dslx() -> iolist().
to_dslx() ->
    to_dslx(3).

-doc "Generates the gateway for a checked or staging topology module.".
-spec to_dslx(1 | 3) -> iolist().
to_dslx(1) ->
    emit(1, phi_noise_topology_smoke, phi_memory_gateway_smoke, 2);
to_dslx(3) ->
    emit(3, phi_noise_topology, phi_memory_gateway, 2);
to_dslx(_Distance) ->
    error(badarg).

-doc "Generates a distance-three gateway for an explicit scheduler profile.".
-spec to_dslx(3, 1 | 2 | {phi_shards, pos_integer()}) -> iolist().
to_dslx(3, SchedulerProfile) ->
    emit(3, phi_noise_topology, phi_memory_gateway, SchedulerProfile);
to_dslx(_Distance, _SchedulerProfile) ->
    error(badarg).

-doc "Forwards optional completed-mailbox observations through the gateway.".
-spec to_dslx(3, 1 | 2 | {phi_shards, pos_integer()}, map()) -> iolist().
to_dslx(3, SchedulerProfile, Options) ->
    emit(3, phi_noise_topology, phi_memory_gateway, SchedulerProfile, Options).

%% Renders a complete checked backend module with its channel interfaces.
-spec emit(
    1 | 3,
    'phi_noise_topology' | 'phi_noise_topology_smoke',
    'phi_memory_gateway' | 'phi_memory_gateway_smoke',
    1 | 2 | {'phi_shards', pos_integer()}
) -> iodata().
emit(Distance, TopologyModule, Artifact, SchedulerProfile) ->
    emit(Distance, TopologyModule, Artifact, SchedulerProfile, #{}).

%% Renders a complete checked backend module with its channel interfaces.
-spec emit(
    1 | 3,
    'phi_noise_topology' | 'phi_noise_topology_smoke',
    'phi_memory_gateway' | 'phi_memory_gateway_smoke',
    1 | 2 | {'phi_shards', pos_integer()},
    map()
) -> iodata().
emit(Distance, TopologyModule, Artifact, SchedulerProfile, Options) ->
    Contract = phi_memory_boundary:contract(Distance),
    RamBindings = scheduler_ram_bindings(SchedulerProfile),
    [
        "// ",
        atom_to_list(Artifact),
        ".x\n",
        "// Auto-generated by phi_memory_gateway_dslx.\n",
        "// Manual changes will be overwritten.\n\n",
        "import axis;\n",
        "import hls_fabric_router;\n",
        "import hls_spatial_router;\n",
        [
            ["import ", Module, ";\n"]
         || Module <- lists:usort([Name || {_Stem, Name} <- RamBindings])
        ],
        "import ",
        atom_to_list(TopologyModule),
        ";\n\n",
        "const WIDTH = u16:",
        integer_to_list(Distance),
        ";\n",
        "const HEIGHT = u16:",
        integer_to_list(Distance),
        ";\n",
        body(TopologyModule, Contract, RamBindings, observation_spec(SchedulerProfile, Options))
    ].

%% Builds gateway framing, routing and topology composition for the selected boundary.
-spec body(
    'phi_noise_topology' | 'phi_noise_topology_smoke', map(), [{[any(), ...], [any()]}], map()
) -> iodata().
body(TopologyModule, Contract, RamBindings, Observation) ->
    [
        boundary_declarations(Contract),
        boundary_policy(Contract),
        spatial_ingress(),
        "\n",
        frame_mux(Contract),
        top_proc(TopologyModule, Contract, RamBindings, Observation)
    ].

%% Defines the host boundary's operation and endpoint selectors.
-spec boundary_declarations(map()) -> iodata().
boundary_declarations(Contract) ->
    [
        "const DATA_HEIGHT = HEIGHT * u16:2;\n",
        boundary_constants(Contract),
        "\n",
        "type BoundaryFrame = axis::FrameN<",
        u32(max_boundary_words(Contract)),
        ">;\n\n"
    ].

%% Resolves the command schemas accepted by a gateway boundary.
-spec boundary_policy(map()) -> iodata().
boundary_policy(Contract) ->
    [
        render_rectangle(),
        "\n",
        render_header_valid(Contract),
        render_rectangle_valid(),
        "\n",
        render_payload_valid(Contract),
        render_boundary_valid(),
        "\n",
        render_inner_payload_words(Contract),
        render_control_target(Contract),
        render_spatial_frame(Contract)
    ].

%% Decodes an inclusive destination rectangle from a host command.
-spec render_rectangle() -> iodata().
render_rectangle() ->
    """
    fn rectangle(frame: BoundaryFrame) -> hls_spatial_router::Rectangle {
      hls_spatial_router::Rectangle {
        x0: frame.payload[0:16] as u16,
        y0: frame.payload[16:32] as u16,
        x1: frame.payload[32:48] as u16,
        y1: frame.payload[48:64] as u16,
      }
    }

    """.

%% Checks command selectors and declared payload lengths.
-spec render_header_valid(map()) -> [[any()], ...].
render_header_valid(Contract) ->
    [
        "fn header_valid(header: axis::Header) -> u1 {\n",
        "  let op_and_words = match header.op {\n",
        header_valid_arms(Contract),
        "\n",
        "    _ => false,\n",
        "  };\n",
        "  header.flags == BOUNDARY_VERSION && header.txid == u8:0 && ",
        "op_and_words\n",
        "}\n\n"
    ].

%% Rejects inverted or out-of-range command rectangles.
-spec render_rectangle_valid() -> iodata().
render_rectangle_valid() ->
    """
    fn rectangle_valid(bounds: hls_spatial_router::Rectangle) -> u1 {
      hls_spatial_router::valid(bounds) &&
        bounds.x1 < WIDTH && bounds.y1 < DATA_HEIGHT
    }

    """.

%% Checks operation-specific command payload constraints.
-spec render_payload_valid(map()) -> [[any()], ...].
render_payload_valid(Contract) ->
    [
        "fn actor_payload_valid(frame: BoundaryFrame) -> u1 {\n",
        "  match frame.header.op {\n",
        payload_valid_arms(Contract),
        "\n",
        "    _ => false,\n",
        "  }\n",
        "}\n\n"
    ].

%% Combines header, rectangle and payload validity before admission.
-spec render_boundary_valid() -> iodata().
render_boundary_valid() ->
    """
    fn boundary_valid(frame: BoundaryFrame) -> u1 {
      header_valid(frame.header) && rectangle_valid(rectangle(frame)) &&
        actor_payload_valid(frame)
    }

    """.

%% Returns the actor payload length for each host command operation.
-spec render_inner_payload_words(map()) -> [[any()], ...].
render_inner_payload_words(Contract) ->
    [
        "fn inner_payload_words(op: u8) -> u8 {\n",
        "  match op {\n",
        inner_word_arms(Contract),
        "\n",
        "    _ => u8:0,\n",
        "  }\n",
        "}\n\n"
    ].

%% Maps a host operation to its topology ingress selector.
-spec render_control_target(map()) -> [[any()], ...].
render_control_target(Contract) ->
    [
        "fn control_target(op: u8) -> u2 {\n",
        "  match op {\n",
        control_target_arms(Contract),
        "\n",
        "    _ => u2:0,\n",
        "  }\n",
        "}\n\n"
    ].

%% Constructs an addressed actor frame from a validated host command.
-spec render_spatial_frame(map()) -> [string(), ...].
render_spatial_frame(Contract) ->
    ActorPayloadEnd = 64 + 32 * max_actor_payload_words(Contract),
    [
        "fn spatial_frame(frame: BoundaryFrame) ->\n",
        "    hls_spatial_router::SpatialFrame {\n",
        "  let inner = axis::Frame {\n",
        "    header: axis::Header {\n",
        "      payload_words: inner_payload_words(frame.header.op),\n",
        "      op: frame.header.op,\n",
        "      ..zero!<axis::Header>()\n",
        "    },\n",
        "    payload: frame.payload[64:",
        integer_to_list(ActorPayloadEnd),
        "] as bits[96],\n",
        "  };\n",
        "  hls_spatial_router::SpatialFrame {\n",
        "    rectangle: rectangle(frame),\n",
        "    target: control_target(frame.header.op),\n",
        "    frame: inner,\n",
        "  }\n",
        "}\n\n"
    ].

%% Assembles a complete command before publishing it to topology ingress.
-spec spatial_ingress() -> iodata().
spatial_ingress() ->
    """
    proc SpatialIngress {
      boundary_in: chan<BoundaryFrame> in;
      spatial_out: chan<hls_spatial_router::SpatialFrame> out;
      arm_out: chan<u1> out;

      config(
          boundary_in: chan<BoundaryFrame> in,
          spatial_out: chan<hls_spatial_router::SpatialFrame> out,
          arm_out: chan<u1> out
      ) {
        (boundary_in, spatial_out, arm_out)
      }

      init { u1:0 }

      next(armed: u1) {
        let (tok, frame) = recv(join(), boundary_in);
        let valid = boundary_valid(frame);
        let arm_tok = send_if(tok, arm_out, valid && !armed, u1:1);
        let _done = send_if(
          arm_tok, spatial_out, valid, spatial_frame(frame));
        armed || valid
      }
    }

    """.

%% Arbitrates complete response frames onto the host output stream.
-spec frame_mux(map()) -> [[any()], ...].
frame_mux(Contract = #{outputs := Outputs}) ->
    OutputCount = length(Outputs),
    [
        "fn source_endpoint(cursor: u32) -> u16 {\n",
        "  match cursor {\n",
        source_endpoint_arms(Contract),
        "\n",
        "  }\n",
        "}\n\n",
        "// Polls one statically indexed input per activation and advances ",
        "after\n",
        "// every attempt, so no continuously active stream can starve ",
        "another.\n",
        "proc FrameMux {\n",
        "  frame_in: chan<axis::Frame>[",
        u32(OutputCount),
        "] in;\n",
        "  routed_out: chan<hls_fabric_router::RoutedFrame> out;\n\n",
        "  config(\n",
        "      frame_in: chan<axis::Frame>[",
        u32(OutputCount),
        "] in,\n",
        "      routed_out: chan<hls_fabric_router::RoutedFrame> out\n",
        "  ) {\n",
        "    (frame_in, routed_out)\n",
        "  }\n\n",
        "  init { u32:0 }\n\n",
        "  next(cursor: u32) {\n",
        "    let (tok, received, frame) =\n",
        "      unroll_for! (candidate, acc):\n",
        "          (u32, (token, u1, axis::Frame)) in u32:0..",
        u32(OutputCount),
        " {\n",
        "        let (next_tok, next_frame, valid) = recv_if_non_blocking(\n",
        "          acc.0,\n",
        "          frame_in[candidate],\n",
        "          cursor == candidate,\n",
        "          zero!<axis::Frame>());\n",
        "        (\n",
        "          next_tok,\n",
        "          acc.1 | valid,\n",
        "          if valid { next_frame } else { acc.2 }\n",
        "        )\n",
        "      }((join(), u1:0, zero!<axis::Frame>()));\n",
        "    let boundary_frame = axis::Frame {\n",
        "      header: axis::Header {\n",
        "        txid: u8:0,\n",
        "        flags: BOUNDARY_VERSION,\n",
        "        ..frame.header\n",
        "      },\n",
        "      ..frame\n",
        "    };\n",
        "    let routed = hls_fabric_router::RoutedFrame {\n",
        "      source: source_endpoint(cursor),\n",
        "      frame: boundary_frame,\n",
        "    };\n",
        "    let _done = send_if(tok, routed_out, received, routed);\n",
        "    if cursor == ",
        u32(OutputCount - 1),
        " { u32:0 } else { cursor + u32:1 }\n",
        "  }\n",
        "}\n\n"
    ].

%% Connects actor services, routers, external ports and startup producers.
-spec top_proc(
    'phi_noise_topology' | 'phi_noise_topology_smoke', map(), [{[any(), ...], [any()]}], map()
) -> [[any()], ...].
top_proc(TopologyModule, Contract = #{outputs := Outputs}, RamBindings, Observation) ->
    OutputCount = length(Outputs),
    RamMembers =
        scheduler_ram_members(RamBindings) ++ xls_scheduler_observation:arguments(Observation),
    RamNames = scheduler_ram_names(RamBindings) ++ xls_scheduler_observation:names(Observation),
    [
        "pub proc Top {\n",
        [["  ", Member, ";\n"] || Member <- RamMembers],
        "  routed_in: chan<axis::Beat> in;\n",
        "  routed_frame_out: chan<hls_fabric_router::RoutedFrame> out;\n\n",
        "  config(\n",
        [["      ", Member, ",\n"] || Member <- RamMembers],
        "      routed_in: chan<axis::Beat> in,\n",
        "      routed_frame_out: chan<hls_fabric_router::RoutedFrame> out\n",
        "  ) {\n",
        "    let (boundary_beats_p, boundary_beats_c) =\n",
        "      chan<axis::Beat, u32:1>(\"boundary_beats\");\n",
        "    let (boundary_frames_p, boundary_frames_c) =\n",
        "      chan<BoundaryFrame, u32:1>(\"boundary_frames\");\n",
        "    let (control_p, control_c) =\n",
        "      chan<hls_spatial_router::SpatialFrame, u32:1>(\"control\");\n",
        "    let (arm_p, arm_c) = chan<u1, u32:1>(\"arm\");\n",
        "    let (topology_outputs_p, topology_outputs_c) =\n",
        "      chan<axis::Frame, u32:0>[",
        u32(OutputCount),
        "](\"topology_outputs\");\n",
        "    let (pre_gate_p, pre_gate_c) =\n",
        "      chan<hls_fabric_router::RoutedFrame, u32:1>(\"pre_gate\");\n",
        "    spawn hls_fabric_router::EndpointIngress<\n",
        "      HOST_ENDPOINT, GATEWAY_ENDPOINT\n",
        "    >(routed_in, boundary_beats_p);\n",
        "    spawn axis::RxN<",
        u32(max_boundary_words(Contract)),
        ">(\n",
        "      boundary_beats_c, boundary_frames_p);\n",
        "    spawn SpatialIngress(boundary_frames_c, control_p, arm_p);\n",
        "    spawn ",
        atom_to_list(TopologyModule),
        "::Top(\n",
        [["      ", Name, ",\n"] || Name <- RamNames],
        "      control_c,\n",
        topology_outputs(Contract),
        ");\n",
        "    spawn FrameMux(topology_outputs_c, pre_gate_p);\n",
        "    spawn hls_fabric_router::EgressGate(\n",
        "      pre_gate_c, routed_frame_out, arm_c);\n",
        "    (",
        join_with(
            ", ",
            RamNames ++
                ["routed_in", "routed_frame_out"]
        ),
        ")\n",
        "  }\n\n",
        "  init { () }\n",
        "  next(state: ()) { state }\n",
        "}\n"
    ].

%% Combines actor and mailbox observation ports for the chosen profile.
-spec observation_spec(1 | 2 | {'phi_shards', pos_integer()}, map()) -> map().
observation_spec(Profile, Options) ->
    #{groups := Groups} = phi_shared_noise_topology_dslx:scheduler_plan(Profile),
    Options#{
        schedulers => [
            #{stem => ["scheduler_", integer_to_list(I)], slot_count => Slots}
         || {I, #{slot_count := Slots}} <- lists:enumerate(0, Groups)
        ]
    }.

%% Declares gateway-facing RAM channels for all executor groups.
-spec scheduler_ram_members([{[any(), ...], [any()]}]) -> [any()].
scheduler_ram_members(RamBindings) ->
    lists:append([
        xls_scheduler_ram_dslx:parameters([Stem, "_"], [Module, "::"])
     || {Stem, Module} <- RamBindings
    ]).

%% Lists gateway RAM endpoints in declaration order.
-spec scheduler_ram_names([{[any(), ...], [any()]}]) -> [any()].
scheduler_ram_names(RamBindings) ->
    lists:append([
        xls_scheduler_ram_dslx:names([Stem, "_"])
     || {Stem, _Module} <- RamBindings
    ]).

%% Retains paired RAM endpoints in the gateway configuration.
-spec scheduler_ram_bindings(1 | 2 | {'phi_shards', pos_integer()}) -> [{[any(), ...], [any()]}].
scheduler_ram_bindings(SchedulerProfile) ->
    #{groups := Groups} = phi_shared_noise_topology_dslx:scheduler_plan(
        SchedulerProfile
    ),
    [
        {["scheduler_", integer_to_list(Index)], atom_to_list(Module)}
     || {Index, #{module := Module}} <- lists:enumerate(0, Groups)
    ].

%% Emits operation and endpoint constants from the boundary schema.
-spec boundary_constants(map()) -> iodata().
boundary_constants(
    #{
        version := Version,
        host_endpoint := Host,
        ingress := #{endpoint := Gateway},
        outputs := Outputs
    } = Contract
) ->
    [
        constant("BOUNDARY_VERSION", "u8", Version),
        constant("HOST_ENDPOINT", "u16", Host),
        constant("GATEWAY_ENDPOINT", "u16", Gateway),
        [
            constant(endpoint_constant(Id), "u16", Endpoint)
         || #{id := Id, endpoint := Endpoint} <- Outputs
        ],
        [
            constant(op_constant(Name), "u8", Selector)
         || #{name := Name, selector := Selector} <- command_schemas(Contract)
        ]
    ].

%% Formats one named constant with its declared DSLX type.
-spec constant(
    nonempty_maybe_improper_list(
        binary() | maybe_improper_list(any(), binary() | []) | char(), binary() | []
    ),
    [49 | 54 | 56 | 117, ...],
    integer()
) -> iodata().
constant(Name, Type, Value) ->
    ["const ", Name, " = ", Type, ":", integer_to_list(Value), ";\n"].

%% Selects the accepted header shape for each operation.
-spec header_valid_arms(map()) -> [any()].
header_valid_arms(Contract) ->
    join_with("\n", [
        [
            "    ",
            op_constant(Name),
            " => header.payload_words == u8:",
            integer_to_list(2 + Words),
            ","
        ]
     || #{name := Name, payload_words := Words} <- command_schemas(Contract)
    ]).

%% Renders operation-specific payload validity branches.
-spec payload_valid_arms(map()) -> [any()].
payload_valid_arms(Contract) ->
    join_with("\n", [payload_valid_arm(Schema) || Schema <- command_schemas(Contract)]).

%% Checks the payload restrictions of one command schema.
-spec payload_valid_arm(map()) -> iodata().
payload_valid_arm(#{name := noise_cutoff}) ->
    ["    ", op_constant(noise_cutoff), " => true,"];
payload_valid_arm(#{name := Name, payload_words := Words}) when
    Name =:= pauli_query; Name =:= pauli_update
->
    Start = 64 + 32 * (Words - 1),
    [
        "    ",
        op_constant(Name),
        " => frame.payload[",
        integer_to_list(Start),
        ":",
        integer_to_list(Start + 32),
        "] as u32 <= u32:3,"
    ].

%% Selects the actor payload word count for each operation.
-spec inner_word_arms(map()) -> [any()].
inner_word_arms(Contract) ->
    join_with("\n", [
        [
            "    ",
            op_constant(Name),
            " => u8:",
            integer_to_list(Words),
            ","
        ]
     || #{name := Name, payload_words := Words} <- command_schemas(Contract)
    ]).

%% Selects the topology target addressed by each host operation.
-spec control_target_arms(map()) -> [any()].
control_target_arms(#{ingress := #{targets := Targets}}) ->
    join_with("\n", [
        [
            "    ",
            op_constant(Name),
            " => u2:",
            integer_to_list(Index),
            ","
        ]
     || #{index := Index, schemas := Schemas} <- Targets,
        #{name := Name} <- Schemas
    ]).

%% Selects the response source endpoint for each boundary output.
-spec source_endpoint_arms(map()) -> [any()].
source_endpoint_arms(#{outputs := Outputs}) ->
    {Initial, [Last]} = lists:split(length(Outputs) - 1, Outputs),
    InitialArms = [
        [
            "    u32:",
            integer_to_list(Index),
            " => ",
            endpoint_constant(Id),
            ","
        ]
     || {Index, #{id := Id}} <- lists:enumerate(0, Initial)
    ],
    LastArm = ["    _ => ", endpoint_constant(maps:get(id, Last)), ","],
    join_with("\n", InitialArms ++ [LastArm]).

%% Lists the output streams exposed by the selected boundary schema.
-spec topology_outputs(map()) -> [any()].
topology_outputs(#{outputs := Outputs}) ->
    join_with(",\n", [
        ["      topology_outputs_p[u32:", integer_to_list(Index), "]"]
     || {Index, _Output} <- lists:enumerate(0, Outputs)
    ]).

%% Returns the largest host command payload length.
-spec max_boundary_words(map()) -> pos_integer().
max_boundary_words(Contract) ->
    2 + max_actor_payload_words(Contract).

%% Returns the largest actor message payload length at the boundary.
-spec max_actor_payload_words(map()) -> non_neg_integer().
max_actor_payload_words(Contract) ->
    lists:max([
        Words
     || #{payload_words := Words} <- command_schemas(Contract)
    ]).

%% Collects the command layouts accepted by this gateway.
-spec command_schemas(map()) -> [map()].
command_schemas(#{ingress := #{targets := Targets}}) ->
    lists:append([maps:get(schemas, Target) || Target <- Targets]).

%% Names a declared boundary endpoint's generated constant.
-spec endpoint_constant(atom()) -> iodata().
endpoint_constant(Id) ->
    string:uppercase(atom_to_list(Id)) ++ "_ENDPOINT".

%% Names a declared command operation's generated constant.
-spec op_constant(atom()) -> iodata().
op_constant(Name) ->
    "OP_" ++ string:uppercase(atom_to_list(Name)).

%% Formats a checked value as an unsigned 32-bit DSLX literal.
-spec u32(integer()) -> [string(), ...].
u32(Value) ->
    ["u32:", integer_to_list(Value)].

%% Interleaves a delimiter without adding a leading or trailing separator.
-spec join_with([10 | 32 | 44, ...], [any()]) -> [any()].
join_with(_Separator, []) -> [];
join_with(Separator, [First | Rest]) -> [First | [[Separator, Item] || Item <- Rest]].
