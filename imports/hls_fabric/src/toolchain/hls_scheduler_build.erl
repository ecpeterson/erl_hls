-module(hls_scheduler_build).
-moduledoc "Packages ordinary channel-scheduled actor topologies with an explicit placement and external schedule. Source generation runs in Erlang; XLS execution remains separate.".
-export([plan/1, descriptor/1, inspect/2, write/2]).
-export_type([config/0, plan/0, descriptor/0, inspection_stage/0, inspection/0, manifest/0]).

-doc "Declared source modules, their trusted topology constructor, physical placement and optional channel schedule. Paths are relative to the caller. Every topology and actor module must be declared; no source is found through an implicit checkout search.".
-type config() :: #{sources := [hls_source_config:source_file(), ...],
    topology := hls_source_config:topology(), placement := xls_shared_topology_profile:profile(),
    schedule => hls_build_profile:schedule_options(), dslx_path => [file:filename()],
    frame_payload_words => hls_frame_layout:words() }.

%% These descriptors identify the loaded source modules; bundle hashes later identify generated bytes.
-type source_descriptor() :: #{module := module(), file := binary(), beam_md5 := binary()}.
%% Requirements are owned by the existing scheduler lowering and passed intact to actor compilation.
-type requirements() :: #{module() => map()}.
%% A plan retains rendered bytes so publication never recompiles source or reloads modules.
-record(plan, {config :: config(), profile :: hls_build_profile:profile(),
    sources :: [source_descriptor()], topology :: hls_topology:plan(),
    scheduler :: hls_scheduler_plan:plan(), generation :: xls_shared_topology_dslx:plan(), requirements :: requirements(),
    bindings :: [map()], files :: hls_generated_files:files(),
    libraries :: [hls_artifact_bundle:library()], unit :: hls_artifact_bundle:unit(),
    cwd :: file:filename()}).

-doc "A checked in-process source build with generated DSLX retained in memory. Planning compiles and loads trusted sources and renders scheduler hardware, but creates no output directory and invokes no XLS tools. Support libraries are copied only when written.".
-opaque plan() :: #plan{}.

-doc "Read-only backend profile, logical topology, checked scheduler placement, prepared generation graph, actor requirements and physical RAM interfaces. Descriptors are inspection data, not saved executable plans or hardware admission.".
-type descriptor() :: #{backend := channel_scheduler, profile := hls_build_profile:profile(),
    topology := hls_topology:plan(), scheduler := hls_scheduler_plan:plan(),
    generation := xls_shared_topology_dslx:descriptor(),
    sources := [source_descriptor()], requirements := requirements(), ram_bindings := [map()]}.

-doc "The shared compiler bundle schema with scheduler backend policy serialized as tagged JSON values. Inputs bind every packaged file; units retain external schedules and RTL lists are indexed by role. Neither eligibility nor native timing is established.".
-type manifest() :: #{version := 1,
    metadata := #{backend := channel_scheduler, profile := hls_diagnostic:json_value()},
    units := [hls_artifact_bundle:unit()], rtl := #{binary() => [binary()]},
    inputs := [#{file := binary(), sha256 := binary()}], eligible := false, native_measured := false}.

-doc "Available views of a retained scheduler build; profile and schedule show the exact policies later packaged for external compilation.".
-type inspection_stage() :: summary | configuration | source | topology | placement | composition | profile | schedule.
-doc "A tagged read-only inspection result; arbitrary Erlang topology identities are diagnostic data, not JSON configuration input.".
-type inspection() :: #{version := 1, backend := channel_scheduler,
    stage := inspection_stage(), data := term()}.

-doc "Validates a trusted configuration, loads each declared source, checks its topology and placement, then renders every required actor and topology into memory. Reuses the normal scheduler lowering and RAM binding authorities. Trusted constructors and parse transforms may have effects; no output files or external tools are created.".
-spec plan(config() | file:filename()) -> plan().
plan(Config) when is_map(Config) ->
    hls_diagnostic:with_context(#{backend => channel_scheduler}, fun() -> prepare(Config) end);
plan(Filename) ->
    hls_diagnostic:with_context(#{backend => channel_scheduler, config_file => text(filename:absname(Filename))},
        fun() -> plan(hls_source_config:read(Filename)) end).

%% Shape and physical-policy errors precede source loading and constructor execution.
-spec prepare(config()) -> plan().
prepare(Config = #{sources := Sources, topology := Constructor, placement := Placement0}) ->
    ok = config_keys(Config),
    _ = hls_source_config:validate_source(maps:with([sources, topology, dslx_path], Config)),
    Layout = hls_frame_layout:new(maps:get(frame_payload_words, Config,
        maps:get(frame_payload_words, Placement0, 3))),
    Placement = xls_shared_topology_profile:normalize(Placement0#{
        frame_payload_words => hls_frame_layout:payload_words(Layout)}),
    Profile = hls_build_profile:scheduler(Placement, maps:get(schedule, Config, #{}), Layout),
    #{libraries := Libraries, imports := Imports} = hls_build_support:layout(maps:get(dslx_path, Config, [])),
    Loaded = load_sources(Sources),
    Topology = topology(Constructor, Loaded),
    Generation = xls_shared_topology_dslx:plan(Topology, Placement),
    Requirements = xls_shared_topology_dslx:artifact_requirements(Generation),
    ok = require_actors(maps:keys(Requirements), Loaded),
    ActorFiles = actors(Requirements, Loaded, Placement),
    TopologyBytes = xls_shared_topology_dslx:emit(Generation),
    Scheduler = hls_scheduler_plan:normalize(Topology, maps:get(scheduler_groups, Placement), Layout),
    Bindings = xls_scheduler_ram_v:bindings(Scheduler, Layout),
    RamFlags = case iolist_to_binary(xls_scheduler_ram_v:configurations(Bindings)) of
        <<>> -> [];
        Flags -> [<<"--ram_configurations=", Flags/binary>>]
    end,
    Unit = unit(Placement, Imports, hls_build_profile:flags(Profile, channel) ++ RamFlags, Bindings),
    Files = hls_generated_files:merge([ActorFiles, ram_files(Bindings), #{
        "scheduler/topology.x" => TopologyBytes,
        "configuration.erl" => io_lib:format("~tp.~n", [Config]),
        "profile.json" => json:encode(hls_diagnostic:json_value(Profile))}]),
    {ok, Cwd} = file:get_cwd(),
    #plan{config = Config, profile = Profile, sources = [D || {D, _} <- Loaded],
        topology = Topology, scheduler = Scheduler, generation = Generation, requirements = Requirements,
        bindings = Bindings, files = Files, libraries = Libraries, unit = Unit, cwd = Cwd};
prepare(Config) ->
    ok = config_keys(Config),
    error(unreachable_scheduler_configuration).

%% Keep the scheduler's supported options closed instead of dropping misspelled keys.
-spec config_keys(map()) -> ok.
config_keys(Config) ->
    Required = [sources, topology, placement],
    case {Required -- maps:keys(Config), maps:keys(Config) -- (Required ++ [schedule, dslx_path, frame_payload_words])} of
        {[], []} -> ok;
        {Missing, Unknown} -> hls_diagnostic:raise(configuration, scheduler_config_fields,
            <<"Scheduler configuration has missing or unsupported fields.">>,
            #{missing => lists:sort(Missing), unsupported => lists:sort(Unknown)})
    end.

-doc "Returns retained source, topology, physical placement, prepared generation graph and profile information without recompiling, rendering or reading source files.".
-spec descriptor(plan()) -> descriptor().
descriptor(#plan{profile = Profile, sources = Sources, topology = Topology,
        scheduler = Scheduler, generation = Generation, requirements = Requirements, bindings = Bindings}) ->
    #{backend => channel_scheduler, profile => Profile, sources => Sources, topology => Topology,
        scheduler => Scheduler, generation => xls_shared_topology_dslx:descriptor(Generation),
        requirements => Requirements, ram_bindings => Bindings}.

-doc "Reports one retained planning view. Schedule contains the exact external compilation units, including RAM configurations. No view executes tools, creates output or resumes a serialized plan.".
-spec inspect(plan(), inspection_stage()) -> inspection().
inspect(Plan, Stage) ->
    #{version => 1, backend => channel_scheduler, stage => Stage, data => inspection_data(Plan, Stage)}.

%% Views retain their owning abstraction instead of exposing the private plan record.
-spec inspection_data(plan(), inspection_stage()) -> term().
inspection_data(#plan{sources = Sources, scheduler = #{groups := Groups, direct_members := Direct}}, summary) ->
    #{backend => channel_scheduler, source_modules => length(Sources), scheduler_groups => length(Groups),
        direct_members => length(Direct), compilation_units => 1, eligible => false, native_measured => false};
inspection_data(#plan{config = Config, cwd = Cwd}, configuration) ->
    #{config => Config, working_directory => text(Cwd)};
inspection_data(#plan{sources = Sources, requirements = Requirements}, source) ->
    #{modules => Sources, requirements => Requirements};
inspection_data(#plan{topology = Topology}, topology) -> Topology;
inspection_data(#plan{scheduler = Scheduler}, placement) -> Scheduler;
inspection_data(Plan, composition) -> descriptor(Plan);
inspection_data(#plan{profile = Profile}, profile) -> Profile;
inspection_data(#plan{unit = Unit}, schedule) -> [Unit].

-doc "Writes retained generated bytes into a fresh directory, snapshots support libraries and freezes source-build.json. It does not reread or recompile declared Erlang sources. RAM fragments expose ordinary external memory ports without inventing an application wrapper; I/O failures retain partial output. XLS, simulations and native timing remain separate.".
-spec write(plan(), file:filename()) -> manifest().
write(#plan{files = Files, libraries = Libraries, unit = Unit, profile = Profile}, Output) ->
    Directory = filename:absname(Output),
    ok = hls_generated_files:write(#{files => Files, result => ok}, Directory),
    ok = hls_artifact_bundle:snapshot(Directory, Libraries),
    #{frame_abi := #{payload_words := Words}} = Profile,
    ok = hls_compile:configure_support(Directory, hls_frame_layout:new(Words)),
    hls_artifact_bundle:finish(Directory, [Unit],
        #{backend => channel_scheduler, profile => hls_diagnostic:json_value(Profile)}).

%% Declared BEAM modules are loaded once and matched to their source filenames explicitly.
-spec load_sources([hls_source_config:source_file()]) -> [{source_descriptor(), file:filename()}].
load_sources(Sources) ->
    Loaded = [load(File, Options) || {File, Options} <- Sources],
    Modules = [Module || {#{module := Module}, _} <- Loaded],
    case length(Modules) =:= length(lists:usort(Modules)) of
        true -> Loaded;
        false -> hls_diagnostic:raise(source, duplicate_scheduler_source,
            <<"Declare each source module once.">>, #{modules => Modules, field => [sources]})
    end.

%% Both backends load source with the same compiler diagnostics and preprocessing context.
-spec load(file:filename(), [hls_source:compiler_option()]) -> {source_descriptor(), file:filename()}.
load(File, Options) ->
    Module = hls_build_sources:load(File, Options),
    {#{module => Module, file => text(File),
        beam_md5 => binary:encode_hex(Module:module_info(md5), lowercase)}, File}.

%% A constructor cannot silently use an undeclared loaded module from a previous build.
-spec topology(hls_source_config:topology(), [{source_descriptor(), file:filename()}]) -> hls_topology:plan().
topology({Module, Function, Arguments}, Loaded) ->
    Modules = [M || {#{module := M}, _} <- Loaded],
    case lists:member(Module, Modules) andalso erlang:function_exported(Module, Function, length(Arguments)) of
        true ->
            Spec = apply(Module, Function, Arguments),
            ok = require_declared_topology(Spec, Loaded),
            hls_topology:normalize(Spec);
        false -> hls_diagnostic:raise(topology, missing_scheduler_constructor,
            <<"Declare and export the configured topology constructor.">>,
            #{module => Module, function => Function, arity => length(Arguments), field => [topology]})
    end.

%% Check source ownership before topology normalization consults actor interface modules.
-spec require_declared_topology(hls_topology:spec(), [{source_descriptor(), file:filename()}]) -> ok.
require_declared_topology(#{actors := Actors, families := Families}, Loaded)
        when is_map(Actors), is_map(Families) ->
    Modules = maps:values(Actors) ++ [M || #{module := M} <- maps:values(Families)],
    require_actors(lists:usort(Modules), Loaded);
require_declared_topology(_, _) -> ok.

%% Requirements cover every distinct actor module, including compact family actors.
-spec require_actors([module()], [{source_descriptor(), file:filename()}]) -> ok.
require_actors(Required, Loaded) ->
    case Required -- [Module || {#{module := Module}, _} <- Loaded] of
        [] -> ok;
        Missing -> hls_diagnostic:raise(source, missing_scheduler_actor_sources,
            <<"Declare every actor module used by the topology.">>, #{modules => Missing, field => [sources]})
    end.

%% Captured preprocessing contexts bind includes and macros consistently with loaded actor interfaces.
-spec actors(requirements(), [{source_descriptor(), file:filename()}], xls_shared_topology_profile:profile()) -> hls_generated_files:files().
actors(Requirements, Loaded, Placement) ->
    Sources = maps:from_list([{Module, File} || {#{module := Module}, File} <- Loaded]),
    Observation = maps:with([mailbox_debug, direct_actor_debug, frame_payload_words], Placement),
    maps:from_list([begin
        File = maps:get(Module, Sources),
        Context = case proplists:get_value(hls_source_context, Module:module_info(attributes)) of
            [Captured] -> Captured;
            undefined -> hls_diagnostic:raise(source, missing_actor_source_context,
                <<"Compile actors with their HLS transform and retain source metadata.">>, #{module => Module})
        end,
        Bytes = xls_shared_parse:to_xls(File, maps:merge(Requirement,
            Observation#{source_options => Context})),
        {"actors/" ++ atom_to_list(Module) ++ ".x", Bytes}
    end || {Module, Requirement} <- lists:sort(maps:to_list(Requirements))]).

%% The generated core leaves external RAM ports visible; fragments are included by an application shell.
-spec ram_files([map()]) -> hls_generated_files:files().
ram_files(Bindings) ->
    #{"ram/bindings.json" => json:encode(Bindings),
      "ram/wires.vh" => xls_scheduler_ram_v:wires(Bindings),
      "ram/application_ports.vh" => xls_scheduler_ram_v:application_ports(Bindings),
      "ram/instances.vh" => xls_scheduler_ram_v:instances(Bindings, "clk")}.

%% Only standalone RTL sources enter files.f; wrapper fragments must not be compiled independently.
-spec unit(xls_shared_topology_profile:profile(), [string()], [binary()], [map()]) -> hls_artifact_bundle:unit().
unit(#{name := Name}, Imports, Flags, Bindings) ->
    RamRtl = case Bindings of
        [] -> [];
        _ -> [<<"support/compiler/rtl/hls_1r1w_ram.v">>] ++ case
            lists:any(fun(B) -> maps:is_key(gather_members, B) end, Bindings) of
                true -> [<<"support/fabric/rtl/hls_indexed_gather_ram.v">>];
                false -> []
            end
    end,
    #{role => <<".">>, directory => <<"scheduler">>, source => <<"scheduler/topology.x">>,
      top => <<"Top">>, module => text(Name), output => <<"scheduler/core.v">>,
      dslx_path => [<<"actors">>, <<"scheduler">> | [text(P) || P <- Imports]],
      codegen_flags => Flags, rtl => [<<"scheduler/core.v">> | RamRtl]}.

%% File and module paths cross JSON boundaries as UTF-8 binaries.
-spec text(unicode:chardata()) -> binary().
text(Value) -> unicode:characters_to_binary(Value).
