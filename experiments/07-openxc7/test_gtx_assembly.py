#!/usr/bin/env python3
"""Exercise assembly boundaries without native tools or retained vendor artifacts."""

import hashlib
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from gtx import assemble, clock_cascades

CHANNEL = "GTX_CHANNEL_1_X186Y17"
COMMON = "GTX_COMMON_X186Y23"
INTERFACE = "GTX_INT_INTERFACE_X73Y17"
OTHER = "GTX_CHANNEL_1_X186Y117"
LOCATIONS = {kind: {"baseaddr": "0x00442480", "word_offset": offset}
             for kind, offset in (("channel", 22), ("common", 0))}
DONOR = {
    "segbits_gtx_channel_1.db": b"GTX_CHANNEL_1.GTXE2_CHANNEL.IN_USE 28_0\n",
    "segbits_gtx_common.db": b"GTX_COMMON.IBUFDS_GTE2_Y1.IN_USE 31_1481\n",
    "ppips_gtx_int_interface.db": b"GTX_INT_INTERFACE.FIXED always\n"}
FASM = CHANNEL + ".GTXE2_CHANNEL.IN_USE\n" + COMMON + ".IBUFDS_GTE2_Y1.IN_USE\n"


def grid() -> dict:
    """Return two measured tiles, an unmeasured lane and a fixed interface."""
    return {tile: {"bits": {}, "type": tile.split("_X")[0]}
            for tile in (CHANNEL, COMMON, INTERFACE, OTHER)}


class AssemblyTests(unittest.TestCase):
    """Require bounded mappings, immutable overlays and independently matching bits."""

    def test_mappings(self) -> None:
        """Never fill other sites or accept a conflicting pre-existing mapping."""
        original = grid()
        mapped = assemble.selected_grid(original, LOCATIONS)
        self.assertFalse(original[CHANNEL]["bits"])
        self.assertEqual(mapped[OTHER], original[OTHER])
        self.assertEqual(mapped[CHANNEL]["bits"]["CLB_IO_CLK"]["offset"], 22)
        with self.assertRaisesRegex(ValueError, "already present"):
            assemble.selected_grid(mapped, LOCATIONS)
        wrong = {**LOCATIONS, "channel": {"baseaddr": "0x00442480", "word_offset": 23}}
        with self.assertRaisesRegex(ValueError, "unexpected measured"):
            assemble.selected_grid(original, wrong)

    def test_scope(self) -> None:
        """Fixed interface wires are legal; other sites, QPLL and unknown bits are not."""
        mapped = assemble.selected_grid(grid(), LOCATIONS)
        assemble.require_scope(mapped, FASM + INTERFACE + ".FIXED\n", DONOR)
        for extra in (OTHER + ".GTXE2_CHANNEL.IN_USE\n", COMMON + ".GTXE2_COMMON.IN_USE\n",
                      COMMON + ".IBUFDS_GTE2_Y0.IN_USE\n", INTERFACE + ".UNKNOWN\n",
                      CHANNEL + ".UNKNOWN\n"):
            with self.subTest(extra=extra), self.assertRaises(ValueError):
                assemble.require_scope(mapped, FASM + extra, DONOR)
        with self.assertRaisesRegex(ValueError, "missing measured"):
            assemble.require_scope(mapped, FASM.splitlines()[0], DONOR)

    def test_matching(self) -> None:
        """Missing, extra and empty evidence cannot count as success."""
        valid = {"enabled_features": 2, "missing_enabled_features": [], "extra_known_bits": []}
        assemble.require_match(valid)
        for bad in ({"enabled_features": 0}, {"missing_enabled_features": ["FIELD"]},
                    {"extra_known_bits": [[1, 2, 3]]}):
            with self.assertRaises(ValueError):
                assemble.require_match({**valid, **bad})

    def test_immutable_overlay(self) -> None:
        """Reuse verifies generated bytes and links while preserving the source grid."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            database = root / "base"
            (database / "xc7z030").mkdir(parents=True)
            (database / assemble.PART).mkdir()
            grid_path = database / "xc7z030/tilegrid.json"
            grid_path.write_text(json.dumps(grid()))
            (database / "xc7z030/tileconn.json").write_text("[]")
            (database / "unmodified.db").write_text("original")
            (database / assemble.PART / "part.yaml").write_text("part")
            pins = {"xc7z030/tilegrid.json": hashlib.sha256(grid_path.read_bytes()).hexdigest(),
                    "xc7z030fbg676-1/part.yaml": hashlib.sha256(b"part").hexdigest()}
            with patch.object(assemble, "DB_SHA256", pins):
                target = assemble.install(database, DONOR, LOCATIONS, root / "overlays")
                self.assertEqual(assemble.install(database, DONOR, LOCATIONS, root / "overlays"), target)
                self.assertEqual(json.loads(grid_path.read_text()), grid())
                self.assertTrue((target / "unmodified.db").is_symlink())
                field = target / "segbits_gtx_channel_1.db"
                field.write_text("corrupt")
                with self.assertRaisesRegex(ValueError, "SHA-256"):
                    assemble.install(database, DONOR, LOCATIONS, root / "overlays")
                field.write_bytes(DONOR[field.name])
                (target / "unmodified.db").unlink()
                (target / "unmodified.db").write_text("original")
                with self.assertRaisesRegex(ValueError, "overlay link"):
                    assemble.install(database, DONOR, LOCATIONS, root / "overlays")

    def test_clock_cascades(self) -> None:
        """Reject contradictory or unrelated donor additions; require both families."""
        known = b"CLK_HROW_BOT_R.EXISTING 1_2\n"
        prefix = "CLK_HROW_BOT_R"
        extra = "\n".join(f"{prefix}.{prefix}_CK_BUFG_CASCO{i}.{prefix}_CK_BUFG_CASCIN{i} 26_{i}"
                          for i in range(32)).encode() + b"\n"
        donor = known + extra
        upper = extra.replace(b"CLK_HROW_BOT_R", b"CLK_HROW_TOP_R")
        result, report = clock_cascades.extend(known, donor, upper)
        self.assertEqual(set(result.splitlines()), set(donor.splitlines()))
        self.assertEqual(report["added_cascades"], 32)
        for bad_donor, bad_upper in ((donor.replace(b"1_2", b"1_3"), upper),
                                      (donor + b"UNRELATED 1_3\n", upper),
                                      (donor, upper.replace(b"26_0", b"28_0")),
                                      (donor, b"")):
            with self.assertRaises(ValueError):
                clock_cascades.extend(known, bad_donor, bad_upper)

    def test_reference_identity(self) -> None:
        """Reject a substituted vendor image before creating artifacts or launching tools."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            reference = root / "wrong.bit"
            reference.write_bytes(b"not the measured reference")
            with self.assertRaisesRegex(ValueError, "vendor reference"):
                assemble.assemble(root, root / "missing.fasm", reference, "ethernet-loopback", root, root / "out")
            self.assertFalse((root / "out").exists())


if __name__ == "__main__":
    unittest.main()
