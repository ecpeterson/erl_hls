-module(xls_gs_immediate).
-moduledoc "Lowers immediate-reply server callbacks into the compact frame service, without retained-call storage.".
-export([emit/2, emit/3]).

-doc "Emits a checked immediate-reply hls_gs service from include-expanded source forms. Validates names, records, payload bounds and callback results; the caller selects this backend only for handle_call/2. Returns DSLX IO data without writing files.".
-spec emit(file:filename(), [hls_source:form()]) -> iolist().
emit(Filename, Forms) -> emit(Filename, Forms, hls_frame_layout:default()).

-doc "Emits the server using an explicit checked ordinary-frame layout and rejects any public schema exceeding it.".
-spec emit(file:filename(), [hls_source:form()], hls_frame_layout:layout()) -> iolist().
emit(Filename, Forms0, Layout) ->
    2 = hls_service_contract:call_arity(Forms0),
    Roots = [{init, 1}, {handle_call, 2}, {handle_cast, 2}],
    Selected = xls_hardware_source:select(Forms0, Roots),
    {SourceForms, Sites} = xls_failure_sites:prepare(Selected),
    {Forms, Helpers} = xls_helpers:prepare(SourceForms, Roots),
    ok = xls_names:actor(Forms, hls_gs),
    PublicStructNames = hls_actor_source:tags(Forms),
    StateName = hls_actor_source:state(Forms),
    StateStructName = xls_names:record_type(StateName),
    Records = hls_records:declarations(Forms, PublicStructNames ++ [StateName]),
    ok = lists:foreach(fun hls_records:validate_defaults/1, Records),
    _ = [hls_actor_source:message_words(Forms, Name, Layout) || Name <- PublicStructNames],

    Preamble = ["// ", Filename, ".x\n",
    """
    // This file is auto-generated by xls_parse. Manual changes will be over-
    // written the next time it is generated. Better to modify the Erlang input.

    """,
    "\n", xls_dslx_imports:emit([axis, hls_failure, hls_bits], xls_dslx_imports:from_forms(Forms)),
    """

    const NOREPLY = u1:0;  // some standard erlang tokens
    const REPLY = u1:1;
    const OK = u1:0;
    const ERROR_FUNCTION_CLAUSE = u32:1;
    const ERROR_REQUEST_LENGTH = u32:3;
    const ERROR_REPLY_CONTRACT = u32:15;


    """,
    hls_frame_layout:assert_dslx(Layout),
    "pub enum Tag : u8 {\n",
    "  NONE = u8:0,\n",
    [
        ["  ", xls_names:enum_member(Atom), " = u8:", integer_to_list(Index), ",\n"]
        ||  {Index, Atom} <- lists:enumerate([error, StateName | PublicStructNames])
    ],
    "}\n\n",
    [[xls_record_codegen:declaration(Record), "\n",
      xls_record_codegen:decoder(Record), "\n",
      xls_record_codegen:encoder(Record), "\n"]
        || Record <- Records]],
    Body = [
    xls_helpers:emit(Helpers, StateName, #{}),
    xls_gs_lower:initial_state(Forms, StateName),
    """
    proc Service {
      req_in:   chan<axis::Frame> in;
      resp_out: chan<axis::Frame> out;
    """, "\n",
    ["  config(req_in: chan<axis::Frame> in, resp_out: chan<axis::Frame> out) {\n",
     "    (req_in, resp_out)\n",
     "  }\n\n"],
    "  init { initial_state() }\n\n",
    ["  next(state: ", StateStructName, ") {\n",
    """
        let (tok1, frame) = recv(join(), req_in);
    """, "\n",
    ["    let state_record = (Tag::", xls_names:enum_member(StateName),
     ", state);\n\n"],
    """
        // cognate to {reply, Reply, State}
        let (resp, new_state) = match frame.header.op as Tag {

    """],
    xls_gs_lower:callback_arms(Forms, StateName, Layout),
    """

        };

        let txid = frame.header.txid;
        let resp2 = axis::Frame { header: axis::Header { txid, ..resp.header }, ..resp };
        send_if(tok1, resp_out, resp2.header.op != (Tag::NONE as u8), resp2);
        new_state.1
      }
    }


    """,
    """
    proc Top {
      ext_recv:  chan<axis::Beat> in;
      ext_send:  chan<axis::Beat> out;
    """, "\n",
    ["  config(ext_recv: chan<axis::Beat> in, ext_send: chan<axis::Beat> out) {\n"],
    """
        let (req_p,  req_c ) = chan<axis::Frame, u32:1>("req");
        let (resp_p, resp_c) = chan<axis::Frame, u32:1>("resp");

        spawn axis::Rx(ext_recv, req_p);
        spawn Service(req_c, resp_p);
        spawn axis::Tx(resp_c, ext_send);

        (ext_recv, ext_send)
      }

      init { () }

      next(state: ()) { state }
    }

    """],

    [xls_clause_lower:print(Preamble), xls_failure_sites:emit(Sites, xls_clause_lower:print(Body))].
