-module(xls_gs_immediate).
-moduledoc "Compiles immediate-reply server callbacks into the compact frame service selected by xls_parse. It prepares the reachable source, delegates callback semantics to xls_gs_lower and finalizes through xls_emitted; retained-call storage and the deferred driver belong to xls_gs_deferred.".
%% Compile an immediate server, retaining metadata or returning bytes.
-export([artifact/3, emit/2, emit/3]).

-doc "Emits a checked immediate-reply hls_gs service from include-expanded source forms. Validates names, records, payload bounds and callback results; the caller selects this backend only for handle_call/2. Returns DSLX IO data without writing files.".
-spec emit(file:filename(), [hls_source:form()]) -> iolist().
emit(Filename, Forms) -> emit(Filename, Forms, hls_frame_layout:default()).

-doc "Emits the server using an explicit checked ordinary-frame layout and rejects any public schema exceeding it.".
-spec emit(file:filename(), [hls_source:form()], hls_frame_layout:layout()) -> iolist().
emit(Filename, Forms, Layout) -> [xls_emitted:bytes(artifact(Filename, Forms, Layout))].

-doc "Finalizes a checked server and its retained failure codebook without writing files.".
-spec artifact(file:filename(), [hls_source:form()], hls_frame_layout:layout()) ->
    xls_emitted:artifact().
artifact(Filename, Forms0, Layout) ->
    2 = hls_service_contract:call_arity(Forms0),
    Roots = [{init, 1}, {handle_call, 2}, {handle_cast, 2}],
    Selected = xls_hardware_source:select(Forms0, Roots),
    {SourceForms, Sites} = xls_failure_sites:prepare(Selected),
    {Forms, Helpers} = xls_helpers:prepare(SourceForms, Roots),
    ok = xls_names:actor(Forms, hls_gs),
    PublicStructNames = hls_actor_source:tags(Forms),
    StateName = hls_actor_source:state(Forms),
    StateStructName = xls_names:record_type(StateName),
    Records = hls_records:declarations(Forms, PublicStructNames ++ [StateName]),
    ok = lists:foreach(fun hls_records:validate_defaults/1, Records),
    _ = [hls_actor_source:message_words(Forms, Name, Layout) || Name <- PublicStructNames],

    Preamble = [
        "// ",
        Filename,
        ".x\n",
        """
        // This file is auto-generated by xls_parse. Manual changes will be over-
        // written the next time it is generated. Better to modify the Erlang input.

        """,
        "\n",
        xls_dslx_imports:emit([axis, hls_failure, hls_bits], xls_dslx_imports:from_forms(Forms)),
        """

        const NOREPLY = u1:0;  // some standard erlang tokens
        const REPLY = u1:1;
        const OK = u1:0;
        const ERROR_FUNCTION_CLAUSE = u32:1;
        const ERROR_REQUEST_LENGTH = u32:3;
        const ERROR_REPLY_CONTRACT = u32:15;


        """,
        xls_frame_layout:assert(Layout),
        "pub enum Tag : u8 {\n",
        "  NONE = u8:0,\n",
        [
            ["  ", xls_names:enum_member(Atom), " = u8:", integer_to_list(Index), ",\n"]
         || {Index, Atom} <- lists:enumerate([error, StateName | PublicStructNames])
        ],
        "}\n\n",
        [
            [
                xls_record_codegen:declaration(Record),
                "\n",
                xls_record_codegen:decoder(Record),
                "\n",
                xls_record_codegen:encoder(Record),
                "\n"
            ]
         || Record <- Records
        ]
    ],
    Body = [
        xls_helpers:emit(Helpers, StateName, #{}),
        xls_gs_lower:initial_state(Forms, StateName),
        "pub struct ServiceState { data: ",
        StateStructName,
        ", failure: u32 }\n",
        "pub struct ServiceResult { response: axis::Frame, state: ServiceState }\n",
        "struct CallbackResult { response: axis::Frame, data: ",
        StateStructName,
        ", error: u32 }\n\n",
        "pub fn initial_service_state() -> ServiceState {\n",
        "  ServiceState { data: initial_state(), failure: u32:0 }\n}\n\n",
        "pub fn service_step(state: ServiceState, frame: axis::Frame) -> ServiceResult {\n",
        "  let state_record = (Tag::",
        xls_names:enum_member(StateName),
        ", state.data);\n",
        "  let outcome = if state.failure != u32:0 {\n",
        "    CallbackResult { data: state.data, error: state.failure, ..zero!<CallbackResult>() }\n",
        "  } else { match frame.header.op {\n",
        xls_gs_lower:callback_arms(Forms, StateName, Layout),
        "\n  } };\n",
        """
          let response = if outcome.error != u32:0 {
            axis::pack(Tag::ERROR as u8, outcome.error)
          } else { outcome.response };
          ServiceResult {
            response: axis::Frame { header: axis::Header { txid: frame.header.txid,
              ..response.header }, ..response },
            state: ServiceState { data: outcome.data,
              failure: if hls_failure::wire_terminal(outcome.error) { outcome.error } else { u32:0 } },
          }
        }

        proc Service {
          req_in: chan<axis::Frame> in;
          resp_out: chan<axis::Frame> out;
          config(req_in: chan<axis::Frame> in, resp_out: chan<axis::Frame> out) {
            (req_in, resp_out)
          }
          init { initial_service_state() }
          next(state: ServiceState) {
            let (tok, frame) = recv(join(), req_in);
            let result = service_step(state, frame);
            send_if(tok, resp_out, result.response.header.op != (Tag::NONE as u8), result.response);
            result.state
          }
        }

        """,
        """
        proc Top {
          ext_recv:  chan<axis::Beat> in;
          ext_send:  chan<axis::Beat> out;
        """,
        "\n",
        ["  config(ext_recv: chan<axis::Beat> in, ext_send: chan<axis::Beat> out) {\n"],
        """
            let (req_p,  req_c ) = chan<axis::Frame, u32:1>("req");
            let (resp_p, resp_c) = chan<axis::Frame, u32:1>("resp");

            spawn axis::Rx(ext_recv, req_p);
            spawn Service(req_c, resp_p);
            spawn axis::Tx(resp_c, ext_send);

            (ext_recv, ext_send)
          }

          init { () }

          next(state: ()) { state }
        }

        """
    ],

    xls_emitted:new(Sites, Preamble, Body, xls_helpers:modules(Helpers, StateName, #{})).
