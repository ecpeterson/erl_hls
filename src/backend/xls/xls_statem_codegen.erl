preamble(#{
    source := Source,
    capacity := Capacity,
    phases := Phases,
    message_names := MessageNames,
    data_name := DataName
}) ->
    [
        "// ", Source, ".x\n",
        "// This file is auto-generated by xls_parse. Manual changes will be\n",
        "// overwritten the next time it is generated.\n\n",
        "import axis;\n",
        "import bram;\n",
        "import mailbox;\n\n",
        "const MAILBOX_CAPACITY = u8:", integer_to_list(Capacity), ";\n",
        "const MAILBOX_DEPTH = u32:", integer_to_list(Capacity), ";\n\n",
        "pub enum Tag : u8 {\n",
        "  NONE = u8:0,\n",
        "  ERROR = u8:1,\n",
        "  ", uppercase(DataName), " = u8:2,\n",
        [
            [
                "  ", uppercase(Name), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Name} <- lists:enumerate(3, MessageNames)
        ],
        "}\n\n",
        phase_declaration(Phases),
        "enum Directive : u2 {\n",
        "  CONSUME = u2:0,\n",
        "  POSTPONE = u2:1,\n",
        "  FAIL = u2:2,\n",
        "}\n\n"
    ].

phase_declaration(Phases) ->
    [
        "enum Phase : u8 {\n",
        [
            [
                "  ", uppercase(Name), " = u8:", integer_to_list(Index),
                ",\n"
            ]
            || {Index, Name} <- lists:enumerate(0, Phases)
        ],
        "}\n\n"
    ].

machine_declarations(#{
    capacity := Capacity,
    output_names := OutputNames,
    max_entry_effects := MaxEntryEffects,
    data_name := DataName,
    data_width := DataWidth
}) ->
    DataStruct = record_struct_name(DataName),
    MachineBits = shared_machine_width(DataWidth),
    EffectCapacity = max(1, MaxEntryEffects),
    [
        "pub enum OutputPort : u8 {\n",
        [
            [
                "  ", uppercase(Port), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Port} <- lists:enumerate(0, OutputNames)
        ],
        "}\n\n",
        "pub struct Egress {\n",
        "  port: OutputPort,\n",
        "  frame: axis::Frame,\n",
        "}\n\n",
        "pub const EGRESS_DEPTH = u32:",
        integer_to_list(EffectCapacity), ";\n\n",
        "pub const ENTRY_EFFECT_CAPACITY = u32:",
        integer_to_list(EffectCapacity), ";\n\n",
        "pub struct EntryEffects {\n",
        "  count: u8,\n",
        "  valid: bool[", integer_to_list(EffectCapacity), "],\n",
        "  values: Egress[", integer_to_list(EffectCapacity), "],\n",
        "}\n\n",
        "type MailboxSlot = mailbox::Slot;\n\n",
        "struct Machine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        "  slots: MailboxSlot[", integer_to_list(Capacity), "],\n",
        "  occupied: u8,\n",
        "  enter_pending: u1,\n",
        "  entry_effect_index: u8,\n",
        "  // Reserves one queue slot for the frame being assembled.\n",
        "  admission_pending: u1,\n",
        "  // A failed service ignores input until reset.\n",
        "  failed: u1,\n",
        "}\n\n",
        "struct SharedMachine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        "  enter_pending: u1,\n",
        "  failed: u1,\n",
        "}\n\n",
        "pub type MachineBits = bits[", integer_to_list(MachineBits), "];\n\n",
        "pub type MachineRamReadReq = bram::ReadReq;\n",
        "pub type MachineRamReadResp = bram::ReadResp<u32:",
        integer_to_list(MachineBits), ">;\n",
        "pub type MachineRamWriteReq = bram::WriteReq<u32:",
        integer_to_list(MachineBits), ">;\n",
        "pub type MachineRamWriteResp = bram::WriteResp;\n\n",
        "pub type MailboxRamReadReq = mailbox::RamReadReq;\n",
        "pub type MailboxRamReadResp = mailbox::RamReadResp;\n",
        "pub type MailboxRamWriteReq = mailbox::RamWriteReq;\n",
        "pub type MailboxRamWriteResp = mailbox::RamWriteResp;\n\n",
        "struct MachineStep {\n",
        "  machine: Machine,\n",
        "  egress: Egress,\n",
        "  egress_valid: u1,\n",
        "  admission_valid: u1,\n",
        "}\n\n",
        "pub type ScheduledRequest = mailbox::ScheduledRequest;\n\n",
        "pub struct ScheduledEffects {\n",
        "  slot: u32,\n",
        "  effects: EntryEffects,\n",
        "}\n\n",
        "struct SharedStep {\n",
        "  machine: SharedMachine,\n",
        "  effects: EntryEffects,\n",
        "  effects_valid: u1,\n",
        "  dispatched: u1,\n",
        "  directive: Directive,\n",
        "  phase_boundary: u1,\n",
        "  egress_blocked: u1,\n",
        "}\n\n",
        "struct SharedDispatch {\n",
        "  machine: SharedMachine,\n",
        "  dispatched: u1,\n",
        "  directive: Directive,\n",
        "  phase_boundary: u1,\n",
        "}\n\n",
        "type Admission = mailbox::Admission;\n\n",
        "enum SharedPhase : u3 {\n",
        "  BOOT = u3:0,\n",
        "  STARTUP = u3:1,\n",
        "  RUN = u3:2,\n",
        "}\n\n",
        "// XLS channel legalization currently confuses multiple otherwise-\n",
        "// identical SharedService instances connected to different external\n",
        "// RAM ports. INSTANCE_ID distinguishes those specializations; it is\n",
        "// neither actor state nor part of scheduling policy.\n",
        "struct SharedState<ACTOR_COUNT: u32, PRODUCER_COUNT: u32> {\n",
        "  instance_id: u32,\n",
        "  phase: SharedPhase,\n",
        "  next_valid: u1,\n",
        "  next_slot: u32,\n",
        "  older_valid: u1,\n",
        "  older_slot: u32,\n",
        "  older_dispatch: SharedDispatch,\n",
        "  older_received: u1,\n",
        "  older_mailbox_index: u8,\n",
        "  older_order_index: u8,\n",
        "  admission_cursor: u32,\n",
        "  cursor: u32,\n",
        "  startup_seen: u32,\n",
        "  pending: ScheduledRequest[PRODUCER_COUNT],\n",
        "  pending_valid: u1[PRODUCER_COUNT],\n",
        "  occupied: u8[ACTOR_COUNT],\n",
        "  order: u8[", integer_to_list(Capacity), "][ACTOR_COUNT],\n",
        "  postponed: u1[", integer_to_list(Capacity), "][ACTOR_COUNT],\n",
        "  // Mailbox work that has not yet been postponed in this phase.\n",
        "  mail_candidates: u1[ACTOR_COUNT],\n",
        "  // Entry work whose effect batch has not yet been classified.\n",
        "  entry_probes: u1[ACTOR_COUNT],\n",
        "  // Entry work known to need the scheduler's batch sequencer.\n",
        "  egress_waiters: u1[ACTOR_COUNT],\n",
        "  egress_busy: u1,\n",
        "  state_write_pending: u1,\n",
        "  mailbox_write_pending: u1,\n",
        "}\n\n"
    ].

-doc false.
-spec shared_machine_width(non_neg_integer()) -> pos_integer().
shared_machine_width(DataWidth) ->
    18 + DataWidth.

