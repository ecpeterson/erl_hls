%%%% xls_statem_codegen
%%%%
%%%% Renders the closed XLS state-machine representation prepared by
%%%% xls_statem_lower. Erlang syntax and parser IR do not cross this boundary.

-module(xls_statem_codegen).
-moduledoc false.

-export([emit/1]).

-type lowered_clause() :: #{
    body := iodata(),
    result := iodata()
}.
-type entry() :: #{
    phase := atom(),
    data := lowered_clause(),
    effects := [map()]
}.
-type cast_clause() :: #{
    tag := atom(),
    phase := atom(),
    body := iodata(),
    result := iodata()
}.
-type spec() :: #{
    source := file:filename(),
    capacity := 1..255,
    phases := [atom(), ...],
    message_names := [atom(), ...],
    message_words := #{atom() := 1..3},
    output_names := [atom(), ...],
    data_name := atom(),
    data_width := pos_integer(),
    record_declarations := iodata(),
    init := lowered_clause(),
    entries := [entry(), ...],
    casts := [cast_clause()]
}.

-spec emit(spec()) -> iolist().
emit(Spec) ->
    [
        preamble(Spec),
        maps:get(record_declarations, Spec),
        machine_declarations(Spec),
        initial_machine(Spec),
        machine_codec(Spec),
        enter_function(Spec),
        dispatch_function(Spec),
        machine_step_function(Spec),
        shared_machine_step_function(Spec),
        service(Spec),
        shared_service(Spec),
        egress_demux(Spec),
        top(Spec)
    ].

