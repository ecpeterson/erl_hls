%% Declares the actor vocabulary and imports optional runtime modules.
-spec preamble(spec()) -> iodata().
preamble(#{
    source := Source,
    imports := Imports,
    capacity := Capacity,
    phases := Phases,
    message_names := MessageNames,
    data_name := DataName
} = Spec) ->
    Reductions = maps:get(reductions, Spec, none),
    [
        "// ", Source, ".x\n",
        "// This file is auto-generated by xls_parse. Manual changes will be\n",
        "// overwritten the next time it is generated.\n\n",
        xls_dslx_imports:emit([axis, bram, mailbox, scheduler, hls_failure, hls_bits] ++
            xls_scheduler_observation:imports(Spec) ++ xls_actor_observation:imports(Spec) ++
            case xls_statem_reply_codegen:enabled(Spec) of true -> [hls_reply]; false -> [] end, Imports),
        "\n",
        "const MAILBOX_CAPACITY = u8:", integer_to_list(Capacity), ";\n",
        "const MAILBOX_DEPTH = u32:", integer_to_list(Capacity), ";\n\n",
        "pub enum Tag : u8 {\n",
        "  NONE = u8:0,\n",
        "  ERROR = u8:1,\n",
        "  ", xls_names:enum_member(DataName), " = u8:2,\n",
        [
            [
                "  ", xls_names:enum_member(Name), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Name} <- lists:enumerate(3, MessageNames)
        ],
        reduction_tag_member(Reductions, MessageNames),
        "}\n\n",
        phase_declaration(Phases),
        "pub enum Directive : u2 {\n",
        "  CONSUME = u2:0,\n",
        "  POSTPONE = u2:1,\n",
        "  FAIL = u2:2,\n",
        "}\n\n"
    ].

reduction_tag_member(none, _MessageNames) ->
    [];
reduction_tag_member(Reductions, MessageNames)
        when length(MessageNames) =< 252 ->
    xls_statem_reduction_codegen:tag_member(
        Reductions,
        3 + length(MessageNames)
    );
reduction_tag_member(_Reductions, MessageNames) ->
    error({too_many_hls_tags_for_reduction, length(MessageNames), 252}).

phase_declaration(Phases) ->
    [
        "enum Phase : u8 {\n",
        [
            [
                "  ", xls_names:enum_member(Name), " = u8:", integer_to_list(Index),
                ",\n"
            ]
            || {Index, Name} <- lists:enumerate(0, Phases)
        ],
        "}\n\n"
    ].

%% Defines state, effects and executor boundaries with only enabled private storage.
-spec machine_declarations(spec()) -> iodata().
machine_declarations(#{
    capacity := Capacity,
    output_names := OutputNames,
    max_entry_effects := MaxEntryEffects,
    message_words := MessageWords,
    entries := Entries,
    data_name := DataName,
    data_width := DataWidth
} = Spec) ->
    Reductions = maps:get(reductions, Spec, none),
    SharedService = maps:get(shared_service, Spec, ordinary),
    ReductionWidth = xls_statem_reduction_codegen:private_width(Reductions),
    DataStruct = xls_names:record_type(DataName),
    EventWidth = event_width(Spec),
    MachineBits = shared_machine_width(DataWidth, ReductionWidth) + EventWidth + xls_statem_reply_codegen:width(Spec),
    EffectCapacity = max(1, MaxEntryEffects),
    EffectPayloadBits = max(entry_effect_payload_bits(Entries, MessageWords),
        case xls_statem_reply_codegen:enabled(Spec) of true -> 128; false -> 0 end),
    [
        "pub enum OutputPort : u8 {\n",
        [
            [
                "  ", xls_names:enum_member(Port), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Port} <- lists:enumerate(0, OutputNames)
        ],
        "}\n\n",
        "pub struct Egress {\n",
        "  port: OutputPort,\n",
        "  frame: axis::Frame,\n",
        "}\n\n",
        "pub const EGRESS_DEPTH = u32:",
        integer_to_list(EffectCapacity), ";\n\n",
        "pub const ENTRY_EFFECT_CAPACITY = u32:",
        integer_to_list(EffectCapacity), ";\n\n",
        "pub const ENTRY_EFFECT_PAYLOAD_BITS = u32:",
        integer_to_list(EffectPayloadBits), ";\n\n",
        "// Sorry: this is a hand-rolled tagged union. DSLX cannot yet express\n",
        "// entry variants whose fields retain their message types.\n",
        "pub struct EntryEffects {\n",
        "  layout: u8,\n",
        "  payloads: bits[", integer_to_list(EffectPayloadBits), "],\n",
        "}\n\n",
        "struct EntryOutcome {\n",
        "  data: ", DataStruct, ",\n",
        "  effects: EntryEffects,\n",
        ?REDUCTION_SERVICE:machine_state_field(Reductions),
        "  failure: hls_failure::Code,\n",
        "}\n\n",
        "type MailboxSlot = mailbox::Slot;\n\n",
        "struct Machine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        ?REDUCTION_SERVICE:machine_state_field(Reductions),
        "  slots: MailboxSlot[", integer_to_list(Capacity), "],\n",
        "  occupied: u8,\n",
        xls_statem_reply_codegen:optional(Spec, "  replies: ReplyBook,\n"),
        xls_statem_event_codegen:optional(Spec, "  next_event: u8,\n"),
        "  enter_pending: u1,\n",
        "  entry_effect_index: u8,\n",
        "  // Reserves one queue slot for the frame being assembled.\n",
        "  admission_pending: u1,\n",
        "  // A failed service ignores input until reset.\n",
        "  failure: hls_failure::Code,\n",
        "}\n\n",
        "struct SharedMachine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        ?REDUCTION_SERVICE:machine_state_field(Reductions),
        xls_statem_reply_codegen:optional(Spec, "  replies: ReplyBook,\n"),
        xls_statem_event_codegen:optional(Spec, "  next_event: u8,\n"),
        "  enter_pending: u1,\n",
        "  failure: hls_failure::Code,\n",
        "}\n\n",
        "pub type MachineBits = bits[", integer_to_list(MachineBits), "];\n\n",
        "pub type MachineRamReadReq = bram::ReadReq;\n",
        "pub type MachineRamReadResp = bram::ReadResp<u32:",
        integer_to_list(MachineBits), ">;\n",
        "pub type MachineRamWriteReq = bram::WriteReq<u32:",
        integer_to_list(MachineBits), ">;\n",
        "pub type MachineRamWriteResp = bram::WriteResp;\n\n",
        "pub type MailboxRamReadReq = mailbox::RamReadReq;\n",
        "pub type MailboxRamReadResp = mailbox::RamReadResp;\n",
        "pub type MailboxRamWriteReq = mailbox::RamWriteReq;\n",
        "pub type MailboxRamWriteResp = mailbox::RamWriteResp;\n\n",
        "struct MachineStep {\n",
        "  machine: Machine,\n",
        "  egress: Egress,\n",
        "  egress_valid: u1,\n",
        "  admission_valid: u1,\n",
        "}\n\n",
        "pub type ScheduledRequest = mailbox::ScheduledRequest;\n\n",
        "pub struct ScheduledEffects {\n",
        "  slot: u32,\n",
        "  effects: EntryEffects,\n",
        "}\n\n",
        "struct SharedStep {\n",
        "  machine: SharedMachine,\n",
        "  effects: EntryEffects,\n",
        "  effects_valid: u1,\n",
        "  dispatched: u1,\n",
        "  directive: Directive,\n",
        "  phase_boundary: u1,\n",
        "  egress_blocked: u1,\n",
        "}\n\n",
        "struct SharedDispatch {\n",
        xls_statem_reply_codegen:optional(Spec, "  reply: axis::Frame,\n  reply_valid: bool,\n"),
        "  machine: SharedMachine,\n",
        "  dispatched: u1,\n",
        "  directive: Directive,\n",
        "  phase_boundary: u1,\n",
        "}\n\n",
        "pub struct SharedExecutorRequest {\n",
        "  slot: u32,\n",
        "  machine: MachineBits,\n",
        "  frame: axis::Frame,\n",
        ?REDUCTION_SERVICE:shared_executor_request_field(
            Reductions, SharedService
        ),
        "  received: u1,\n",
        "  mailbox_index: u8,\n",
        "  order_index: u8,\n",
        "  egress_ready: u1,\n",
        "}\n\n",
        "pub struct SharedExecutorResult {\n",
        "  slot: u32,\n",
        "  machine: MachineBits,\n",
        "  effects: EntryEffects,\n",
        "  effects_valid: u1,\n",
        "  dispatched: u1,\n",
        "  directive: Directive,\n",
        "  phase_boundary: u1,\n",
        "  egress_blocked: u1,\n",
        "  received: u1,\n",
        "  mailbox_index: u8,\n",
        "  order_index: u8,\n",
        "}\n\n",
        "enum SharedPhase : u3 {\n",
        "  BOOT = u3:0,\n",
        "  STARTUP = u3:1,\n",
        "  RUN = u3:2,\n",
        "}\n\n",
        "// XLS channel legalization currently confuses multiple otherwise-\n",
        "// identical SharedService instances connected to different external\n",
        "// RAM ports. INSTANCE_ID distinguishes those specializations; it is\n",
        "// neither actor state nor part of scheduling policy.\n",
        "struct SharedState<ACTOR_COUNT: u32, PRODUCER_COUNT: u32> {\n",
        "  instance_id: u32,\n",
        "  phase: SharedPhase,\n",
        "  next_valid: u1,\n",
        "  next_slot: u32,\n",
        "  in_flight: u1[ACTOR_COUNT],\n",
        ?REDUCTION_SERVICE:shared_state_fields(Reductions, SharedService),
        "  completed_valid: u1,\n",
        "  completed: SharedExecutorResult,\n",
        "  admission_cursor: u32,\n",
        "  cursor: u32,\n",
        "  startup_seen: u32,\n",
        "  pending: ScheduledRequest[PRODUCER_COUNT],\n",
        "  pending_valid: u1[PRODUCER_COUNT],\n",
        "  occupied: u8[ACTOR_COUNT],\n",
        "  order: u8[", integer_to_list(Capacity), "][ACTOR_COUNT],\n",
        "  postponed: u1[", integer_to_list(Capacity), "][ACTOR_COUNT],\n",
        "  // Mailbox work that has not yet been postponed in this phase.\n",
        "  mail_candidates: u1[ACTOR_COUNT],\n",
        "  // Entry work whose effect batch has not yet been classified.\n",
        "  entry_probes: u1[ACTOR_COUNT],\n",
        "  // Entry work known to need the scheduler's batch sequencer.\n",
        "  egress_waiters: u1[ACTOR_COUNT],\n",
        "  egress_busy: u1,\n",
        "  state_write_pending: u1,\n",
        "  mailbox_write_pending: u1,\n",
        "}\n\n"
    ].

-doc false.
-spec shared_machine_width(non_neg_integer()) -> pos_integer().
shared_machine_width(DataWidth) ->
    shared_machine_width(DataWidth, 0).

-doc false.
-spec shared_machine_width(non_neg_integer(), non_neg_integer()) ->
    pos_integer().
shared_machine_width(DataWidth, ReductionWidth) ->
    maps:get(width, shared_machine_layout(DataWidth, ReductionWidth)).

%% Low-to-high packed RAM layout, shared by the codec and passive debug taps.
-spec shared_machine_layout(non_neg_integer(), non_neg_integer()) -> map().
shared_machine_layout(DataWidth, ReductionWidth) ->
    {Width, Fields} = lists:foldl(fun({Name, Bits}, {Offset, Acc}) ->
        {Offset + Bits, Acc#{Name => #{offset => Offset, width => Bits}}}
    end, {0, #{}}, [{phase, 8}, {entered_from, 8}, {data, DataWidth},
        {enter_pending, 1}, {failure, 16}, {reduction, ReductionWidth}]),
    Fields#{width => Width}.

