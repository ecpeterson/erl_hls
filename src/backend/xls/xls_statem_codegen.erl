%%%% xls_statem_codegen
%%%%
%%%% Renders the closed XLS state-machine representation prepared by
%%%% xls_statem_lower. Erlang syntax and parser IR do not cross this boundary.

-module(xls_statem_codegen).
-moduledoc false.

-export([emit/1, shared_machine_width/1, shared_machine_width/2, shared_machine_layout/2, entry_value/5]).

-define(REDUCTION_SERVICE, xls_statem_reduction_service_codegen).

-type entry() :: #{
    phase := atom(),
    evaluation := #{body := iodata(), result := iodata(), failed := iodata()},
    layouts := [map()]
}.
-type cast_clause() :: #{
    tag := atom(),
    phase := atom(),
    body := iodata(),
    result := iodata()
}.
%% Complete renderer input, including the emitted failure-site catalog.
-type spec() :: #{
    failure_sites := [map()],
    source := file:filename(),
    imports := [atom()],
    capacity := 1..255,
    phases := [atom(), ...],
    message_names := [atom(), ...],
    message_words := #{atom() => 0..3},
    output_names := [atom(), ...],
    data_name := atom(),
    data_width := non_neg_integer(),
    record_declarations := iodata(),
    helper_functions := iodata(),
    init := xls_init:lowered(),
    entries := [entry(), ...],
    max_entry_effects := non_neg_integer(),
    casts := [cast_clause()],
    continuations := [atom()],
    internal_steps := [map()],
    retained_calls := none | map(),
    reductions := none | xls_statem_reduction_ir:reduction(),
    shared_service := ordinary | aggregate_only,
    mailbox_debug => boolean(),
    direct_actor_debug => boolean()
}.

-doc "Renders validated actor callbacks as singleton and shared-scheduler DSLX services.".
-spec emit(spec()) -> iolist().
emit(Spec) ->
    SharedService = maps:get(shared_service, Spec, ordinary),
    Body = [
        maps:get(record_declarations, Spec),
        maps:get(helper_functions, Spec),
        xls_statem_reduction_codegen:declarations(
            maps:get(reductions, Spec, none), SharedService
        ),
        xls_statem_reply_codegen:declarations(Spec),
        machine_declarations(Spec),
        xls_actor_observation:declarations(Spec),
        xls_statem_reduction_codegen:functions(
            maps:get(reductions, Spec, none), SharedService
        ),
        initial_machine(Spec),
        machine_codec(Spec),
        enter_function(Spec),
        entry_effects_valid_function(),
        xls_statem_reply_codegen:functions(Spec),
        dispatch_function(Spec),
        xls_statem_event_codegen:functions(Spec),
        machine_step_function(Spec),
        shared_machine_step_function(Spec),
        shared_executor(Spec),
        service(Spec),
        shared_service(Spec),
        egress_demux(Spec),
        top(Spec)
    ],
    [preamble(Spec), xls_failure_sites:emit(maps:get(failure_sites, Spec, []), Body)].

