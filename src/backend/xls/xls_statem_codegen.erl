preamble(#{
    source := Source,
    capacity := Capacity,
    phases := Phases,
    message_names := MessageNames,
    data_name := DataName
}) ->
    [
        "// ", Source, ".x\n",
        "// This file is auto-generated by xls_parse. Manual changes will be\n",
        "// overwritten the next time it is generated.\n\n",
        "import axis;\n\n",
        "const MAILBOX_CAPACITY = u8:", integer_to_list(Capacity), ";\n",
        "const MAILBOX_DEPTH = u32:", integer_to_list(Capacity), ";\n\n",
        "pub enum Tag : u8 {\n",
        "  NONE = u8:0,\n",
        "  ERROR = u8:1,\n",
        "  ", uppercase(DataName), " = u8:2,\n",
        [
            [
                "  ", uppercase(Name), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Name} <- lists:enumerate(3, MessageNames)
        ],
        "}\n\n",
        phase_declaration(Phases),
        "enum Directive : u2 {\n",
        "  CONSUME = u2:0,\n",
        "  POSTPONE = u2:1,\n",
        "  FAIL = u2:2,\n",
        "}\n\n"
    ].

phase_declaration(Phases) ->
    [
        "enum Phase : u8 {\n",
        [
            [
                "  ", uppercase(Name), " = u8:", integer_to_list(Index),
                ",\n"
            ]
            || {Index, Name} <- lists:enumerate(0, Phases)
        ],
        "}\n\n"
    ].

machine_declarations(#{
    capacity := Capacity,
    output_names := OutputNames,
    max_entry_effects := MaxEntryEffects,
    data_name := DataName,
    data_width := DataWidth
}) ->
    DataStruct = record_struct_name(DataName),
    MachineBits = shared_machine_bits(DataWidth),
    [
        "pub enum OutputPort : u8 {\n",
        [
            [
                "  ", uppercase(Port), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Port} <- lists:enumerate(0, OutputNames)
        ],
        "}\n\n",
        "pub struct Egress {\n",
        "  port: OutputPort,\n",
        "  frame: axis::Frame,\n",
        "}\n\n",
        "pub const EGRESS_DEPTH = u32:",
        integer_to_list(max(1, MaxEntryEffects)), ";\n\n",
        "struct EntryEffects {\n",
        "  count: u8,\n",
        "  valid: bool[", integer_to_list(length(OutputNames)), "],\n",
        "  values: Egress[", integer_to_list(length(OutputNames)), "],\n",
        "}\n\n",
        "struct MailboxSlot {\n",
        "  postponed: u1,\n",
        "  frame: axis::Frame,\n",
        "}\n\n",
        "struct Machine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        "  slots: MailboxSlot[", integer_to_list(Capacity), "],\n",
        "  occupied: u8,\n",
        "  enter_pending: u1,\n",
        "  entry_effect_index: u8,\n",
        "  // Reserves one queue slot for the frame being assembled.\n",
        "  admission_pending: u1,\n",
        "  // A failed service ignores input until reset.\n",
        "  failed: u1,\n",
        "}\n\n",
        "struct SharedMachine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        "  enter_pending: u1,\n",
        "  entry_effect_index: u8,\n",
        "  failed: u1,\n",
        "}\n\n",
        "pub type MachineBits = bits[", integer_to_list(MachineBits), "];\n\n",
        "pub struct MachineRamReq {\n",
        "  addr: u32,\n",
        "  data: MachineBits,\n",
        "  write_mask: (),\n",
        "  read_mask: (),\n",
        "  we: u1,\n",
        "  re: u1,\n",
        "}\n\n",
        "pub struct MachineRamResp { data: MachineBits }\n\n",
        "pub struct MailboxRamReq {\n",
        "  addr: u32,\n",
        "  data: bits[128],\n",
        "  write_mask: (),\n",
        "  read_mask: (),\n",
        "  we: u1,\n",
        "  re: u1,\n",
        "}\n\n",
        "pub struct MailboxRamResp { data: bits[128] }\n\n",
        "struct MachineStep {\n",
        "  machine: Machine,\n",
        "  egress: Egress,\n",
        "  egress_valid: u1,\n",
        "  admission_valid: u1,\n",
        "}\n\n",
        "pub struct ScheduledRequest {\n",
        "  slot: u32,\n",
        "  frame: axis::Frame,\n",
        "  credit: u1,\n",
        "}\n\n",
        "pub struct ScheduledEgress {\n",
        "  slot: u32,\n",
        "  egress: Egress,\n",
        "}\n\n",
        "struct SharedStep {\n",
        "  machine: SharedMachine,\n",
        "  egress: Egress,\n",
        "  egress_valid: u1,\n",
        "  dispatched: u1,\n",
        "  directive: Directive,\n",
        "  phase_boundary: u1,\n",
        "}\n\n",
        "enum SharedPhase : u3 {\n",
        "  BOOT = u3:0,\n",
        "  STARTUP = u3:1,\n",
        "  COLLECT = u3:2,\n",
        "  READ = u3:3,\n",
        "  EXECUTE = u3:4,\n",
        "}\n\n",
        "struct SharedState<ACTOR_COUNT: u32, PRODUCER_COUNT: u32> {\n",
        "  phase: SharedPhase,\n",
        "  slot: u32,\n",
        "  machine: SharedMachine,\n",
        "  frame: axis::Frame,\n",
        "  received: u1,\n",
        "  mailbox_index: u8,\n",
        "  order_index: u8,\n",
        "  cursor: u32,\n",
        "  startup_seen: u32,\n",
        "  pending: ScheduledRequest[PRODUCER_COUNT],\n",
        "  pending_valid: u1[PRODUCER_COUNT],\n",
        "  occupied: u8[ACTOR_COUNT],\n",
        "  order: u8[", integer_to_list(Capacity), "][ACTOR_COUNT],\n",
        "  postponed: u1[", integer_to_list(Capacity), "][ACTOR_COUNT],\n",
        "  egress_busy: u1,\n",
        "}\n\n"
    ].

shared_machine_bits(DataWidth) ->
    26 + DataWidth.

