initial_machine(#{init := #{body := Body, result := Result}}) ->
    [
        "fn initial_machine() -> Machine {\n",
        Body,
        "  ", Result, "\n",
        "}\n\n",
        "fn shared_machine(machine: Machine) -> SharedMachine {\n",
        "  SharedMachine {\n",
        "    phase: machine.phase,\n",
        "    entered_from: machine.entered_from,\n",
        "    data: machine.data,\n",
        "    enter_pending: machine.enter_pending,\n",
        "    entry_effect_index: machine.entry_effect_index,\n",
        "    failed: machine.failed,\n",
        "  }\n",
        "}\n\n",
        "fn initial_shared_machine() -> SharedMachine {\n",
        "  shared_machine(initial_machine())\n",
        "}\n\n"
    ].

machine_codec(#{capacity := Capacity, data_name := DataName,
        data_width := DataWidth}) ->
    DataStart = 16,
    EnterStart = DataStart + DataWidth,
    EffectStart = EnterStart + 1,
    FailedStart = EffectStart + 8,
    DataFunction = record_function_name(DataName),
    [
        "fn axis_frame_from_bits(raw: bits[128]) -> axis::Frame {\n",
        "  axis::Frame {\n",
        "    header: axis::Header {\n",
        "      payload_words: raw[0:8],\n",
        "      txid: raw[8:16],\n",
        "      flags: raw[16:24],\n",
        "      op: raw[24:32],\n",
        "    },\n",
        "    payload: raw[32:128],\n",
        "  }\n",
        "}\n\n",
        "fn bits_from_axis_frame(frame: axis::Frame) -> bits[128] {\n",
        "  frame.payload ++ (frame.header.op as bits[8]) ++\n",
        "    (frame.header.flags as bits[8]) ++\n",
        "    (frame.header.txid as bits[8]) ++\n",
        "    (frame.header.payload_words as bits[8])\n",
        "}\n\n",
        "fn machine_from_bits(raw: MachineBits) -> SharedMachine {\n",
        "  SharedMachine {\n",
        "    phase: raw[0:8] as Phase,\n",
        "    entered_from: raw[8:16] as Phase,\n",
        "    data: ", DataFunction, "_from_bits(raw[",
        integer_to_list(DataStart), ":", integer_to_list(EnterStart), "]),\n",
        "    enter_pending: raw[", integer_to_list(EnterStart), ":",
        integer_to_list(EffectStart), "],\n",
        "    entry_effect_index: raw[", integer_to_list(EffectStart), ":",
        integer_to_list(FailedStart), "],\n",
        "    failed: raw[", integer_to_list(FailedStart), ":",
        integer_to_list(FailedStart + 1), "],\n",
        "  }\n",
        "}\n\n",
        "fn bits_from_machine(machine: SharedMachine) -> MachineBits {\n",
        "  machine.failed ++\n",
        "    (machine.entry_effect_index as bits[8]) ++\n",
        "    machine.enter_pending ++\n",
        "    bits_from_", DataFunction, "(machine.data) ++\n",
        "    (machine.entered_from as bits[8]) ++\n",
        "    (machine.phase as bits[8])\n",
        "}\n\n",
        "fn machine_read(slot: u32) -> MachineRamReq {\n",
        "  MachineRamReq {\n",
        "    addr: slot,\n",
        "    re: u1:1,\n",
        "    ..zero!<MachineRamReq>()\n",
        "  }\n",
        "}\n\n",
        "fn machine_write(slot: u32, machine: SharedMachine) -> MachineRamReq {\n",
        "  MachineRamReq {\n",
        "    addr: slot,\n",
        "    data: bits_from_machine(machine),\n",
        "    we: u1:1,\n",
        "    ..zero!<MachineRamReq>()\n",
        "  }\n",
        "}\n\n",
        "fn mailbox_addr(slot: u32, index: u8) -> u32 {\n",
        "  slot * u32:", integer_to_list(Capacity), " + index as u32\n",
        "}\n\n",
        "fn mailbox_read(slot: u32, index: u8) -> MailboxRamReq {\n",
        "  MailboxRamReq {\n",
        "    addr: mailbox_addr(slot, index),\n",
        "    re: u1:1,\n",
        "    ..zero!<MailboxRamReq>()\n",
        "  }\n",
        "}\n\n",
        "fn mailbox_write(\n",
        "    slot: u32, index: u8, frame: axis::Frame) -> MailboxRamReq {\n",
        "  MailboxRamReq {\n",
        "    addr: mailbox_addr(slot, index),\n",
        "    data: bits_from_axis_frame(frame),\n",
        "    we: u1:1,\n",
        "    ..zero!<MailboxRamReq>()\n",
        "  }\n",
        "}\n\n"
    ].

enter_function(#{
    data_name := DataName,
    output_names := OutputNames,
    entries := Entries
}) ->
    DataStruct = record_struct_name(DataName),
    [
        "fn enter(old_phase: Phase, phase: Phase, data: ", DataStruct,
        ") -> (", DataStruct, ", EntryEffects) {\n",
        "  match phase {\n",
        [entry_arm(Entry, OutputNames) || Entry <- Entries],
        "  }\n",
        "}\n\n"
    ].

entry_arm(#{
    phase := Phase,
    data := #{body := DataBody, result := DataResult},
    effects := Effects
}, OutputNames) ->
    Padding = length(OutputNames) - length(Effects),
    [
        "    Phase::", uppercase(Phase), " => {\n",
        "      let entered_data = {\n",
        xls_parse_io:indent(DataBody, 8),
        "        ", DataResult, "\n",
        "      };\n",
        [entry_effect_binding(Index, Effect)
            || {Index, Effect} <- lists:enumerate(0, Effects)],
        "      (entered_data, EntryEffects {\n",
        "        count: u8:", integer_to_list(length(Effects)), ",\n",
        "        valid: [\n",
        [
            ["          effect_", integer_to_list(Index), "_valid,\n"]
            || {Index, _Effect} <- lists:enumerate(0, Effects)
        ],
        lists:duplicate(Padding, "          bool:false,\n"),
        "        ],\n",
        "        values: [\n",
        [
            [
                "          Egress { port: OutputPort::",
                uppercase(maps:get(port, Effect)),
                ", frame: effect_", integer_to_list(Index), " },\n"
            ]
            || {Index, Effect} <- lists:enumerate(0, Effects)
        ],
        lists:duplicate(Padding, "          zero!<Egress>(),\n"),
        "        ],\n",
        "      })\n",
        "    },\n"
    ].

entry_effect_binding(Index, #{
    body := Body,
    result := Result,
    valid := #{body := ValidBody, result := ValidResult}
}) ->
    [
        "      let effect_", integer_to_list(Index), "_valid = {\n",
        xls_parse_io:indent(ValidBody, 8),
        "        ", ValidResult, "\n",
        "      };\n",
        "      let effect_", integer_to_list(Index), " = {\n",
        xls_parse_io:indent(Body, 8),
        "        ", Result, "\n",
        "      };\n"
    ].

dispatch_function(#{
    message_names := MessageNames,
    data_name := DataName,
    casts := Casts
}) ->
    DataStruct = record_struct_name(DataName),
    [
        "fn dispatch(frame: axis::Frame, phase: Phase, data: ", DataStruct,
        ") -> (Phase, ", DataStruct, ", Directive, u1) {\n",
        "  match frame.header.op as Tag {\n",
        [dispatch_tag_arm(Name, Casts) || Name <- MessageNames],
        "    _ => (phase, data, Directive::FAIL, u1:0),\n",
        "  }\n",
        "}\n\n"
    ].

dispatch_tag_arm(Tag, Casts) ->
    TagCasts = [Cast || Cast <- Casts, maps:get(tag, Cast) =:= Tag],
    [
        "    Tag::", uppercase(Tag), " => {\n",
        "      let message = ", record_function_name(Tag),
        "_from_bits(frame.payload);\n",
        "      match phase {\n",
        [dispatch_phase_arm(Cast) || Cast <- TagCasts],
        "        _ => (phase, data, Directive::FAIL, u1:0),\n",
        "      }\n",
        "    },\n"
    ].

dispatch_phase_arm(#{
    phase := Phase,
    body := Body,
    result := Result
}) ->
    [
        "        Phase::", uppercase(Phase), " => {\n",
        xls_parse_io:indent(Body, 10),
        xls_parse_io:indent(Result, 10),
        "        },\n"
    ].

