name(Atom) ->
    atom_to_list(Atom).

separator(Index, Count) when Index + 1 < Count -> ",";
separator(_Index, _Count) -> "".

join_with(_Separator, []) ->
    [];
join_with(Separator, [First | Rest]) ->
    [First | [[Separator, Item] || Item <- Rest]].

%% The selector is present for finite events and for the shared retained-call outcome.
-spec event_width(map()) -> 0 | 8.
event_width(Spec) -> case maps:get(continuations, Spec, []) =/= [] orelse xls_statem_reply_codegen:enabled(Spec) of true -> 8; false -> 0 end.

%% Replies use the existing effect sequencer with one reserved frame layout.
-spec reply_layout_count(map()) -> iodata().
reply_layout_count(Spec) -> case xls_statem_reply_codegen:enabled(Spec) of
    false -> [];
    true -> ["    u8:", integer_to_list(xls_statem_reply_codegen:layout(Spec)), " => u8:1,\n"]
end.

%% The reply carries its original transaction ID through ordinary topology routing.
-spec reply_layout_effect(map()) -> iodata().
reply_layout_effect(Spec = #{retained_calls := #{port := Port}}) ->
    ["    u8:", integer_to_list(xls_statem_reply_codegen:layout(Spec)),
     " => Egress { port: OutputPort::", xls_names:enum_member(Port),
     ", frame: axis::frame_from_bits(effects.payloads as bits[128]) },\n"];
reply_layout_effect(_) -> [].

%% Caller-contract faults become actor failures without publishing the invalid reply.
-spec reply_failure_binding(map()) -> iodata().
reply_failure_binding(Spec) -> xls_statem_reply_codegen:optional(Spec,
    "    let contract_fault = failure == hls_failure::NONE && reply_book.failure == u32:15;\n"
    "    let failure = hls_failure::first(failure, if reply_book.failure != u32:0 { hls_failure::REPLY_CONTRACT } else { hls_failure::NONE });\n"
    "    let failed = hls_failure::failed(failure);\n").

%% Singleton outputs commit together with their checked callback state.
-spec direct_reply_effect(map()) -> iodata().
direct_reply_effect(Spec = #{retained_calls := #{port := Port}}) ->
    xls_statem_reply_codegen:optional(Spec, ["      egress: Egress { port: OutputPort::", xls_names:enum_member(Port),
        ", frame: response }, egress_valid: response_valid,\n"]);
direct_reply_effect(_) -> [].

%% A reply precedes phase entry; that entry remains pending for the next activation.
-spec shared_reply_effect(map()) -> iodata().
shared_reply_effect(Spec) -> case xls_statem_reply_codegen:enabled(Spec) of
    false -> [];
    true -> ["if dispatched.reply_valid { SharedStep { machine: dispatched.machine, effects: ",
        xls_statem_reply_codegen:effect(Spec), ", effects_valid: true, ..zero!<SharedStep>() } } else { "]
end.

%% Failed actors retire outstanding callers serially without executing application code.
-spec direct_failure_step(map()) -> iodata().
direct_failure_step(#{retained_calls := #{port := Port}}) ->
    ["    let admitted_slots = if received { update(machine.slots, machine.occupied as u32, MailboxSlot { frame, ..zero!<MailboxSlot>() }) } else { machine.slots };\n",
     "    let occupied = machine.occupied + received as u8;\n",
     "    let step = shared_machine_reply_failure(shared_machine(machine), admitted_slots[u32:0].frame, occupied != u8:0);\n",
     "    let commit = !step.reply_valid || egress_ready;\n",
     "    let consume = step.dispatched && commit;\n",
     "    let remaining = occupied - consume as u8;\n",
     "    let slots = unroll_for! (i, slots): (u32, MailboxSlot[MAILBOX_DEPTH]) in u32:0..MAILBOX_DEPTH {\n",
     "      update(slots, i, if consume && i + u32:1 < occupied as u32 { admitted_slots[i + u32:1] } else { admitted_slots[i] })\n",
     "    }(admitted_slots);\n",
     "    let pending = machine.admission_pending && !received;\n",
     "    let reserve = !pending && !received && remaining < MAILBOX_CAPACITY;\n",
     "    MachineStep { machine: Machine { replies: if commit { step.machine.replies } else { machine.replies },\n",
     "        occupied: remaining, slots, next_event: u8:0, enter_pending: false, admission_pending: pending || reserve, ..machine },\n",
     "      egress: Egress { port: OutputPort::", xls_names:enum_member(Port), ", frame: step.reply },\n",
     "      egress_valid: step.reply_valid && commit, admission_valid: reserve, ..zero!<MachineStep>() }\n"];
direct_failure_step(_) -> "    MachineStep { machine, ..zero!<MachineStep>() }\n".

