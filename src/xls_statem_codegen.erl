%%%% xls_statem_codegen
%%%%
%%%% Renders the closed XLS state-machine representation prepared by
%%%% xls_statem_lower. Erlang syntax and parser IR do not cross this boundary.

-module(xls_statem_codegen).
-moduledoc false.

-export([emit/1]).

-type lowered_clause() :: #{
    body := iodata(),
    result := iodata()
}.
-type entry() :: #{
    phase := atom(),
    data := lowered_clause(),
    outputs := #{atom() := map()}
}.
-type cast_clause() :: #{
    tag := atom(),
    phase := atom(),
    body := iodata(),
    result := iodata()
}.
-type spec() :: #{
    source := file:filename(),
    capacity := 1..255,
    phases := [atom(), ...],
    message_names := [atom(), ...],
    message_words := #{atom() := 1..3},
    output_names := [atom(), ...],
    data_name := atom(),
    record_declarations := iodata(),
    init := lowered_clause(),
    entries := [entry(), ...],
    casts := [cast_clause()]
}.

-spec emit(spec()) -> iolist().
emit(Spec) ->
    [
        preamble(Spec),
        maps:get(record_declarations, Spec),
        machine_declarations(Spec),
        initial_machine(Spec),
        enter_function(Spec),
        dispatch_function(Spec),
        service(Spec),
        top(Spec)
    ].

%%%
%%% Module declarations
%%%

preamble(#{
    source := Source,
    capacity := Capacity,
    phases := Phases,
    message_names := MessageNames,
    data_name := DataName
}) ->
    [
        "// ", Source, ".x\n",
        "// This file is auto-generated by xls_parse. Manual changes will be\n",
        "// overwritten the next time it is generated.\n\n",
        "import axis;\n\n",
        "const MAILBOX_CAPACITY = u8:", integer_to_list(Capacity), ";\n\n",
        "pub enum Tag : u8 {\n",
        "  NONE = u8:0,\n",
        "  ERROR = u8:1,\n",
        "  ", uppercase(DataName), " = u8:2,\n",
        [
            [
                "  ", uppercase(Name), " = u8:",
                integer_to_list(Index), ",\n"
            ]
            || {Index, Name} <- lists:enumerate(3, MessageNames)
        ],
        "}\n\n",
        phase_declaration(Phases),
        "enum Directive : u2 {\n",
        "  CONSUME = u2:0,\n",
        "  POSTPONE = u2:1,\n",
        "  FAIL = u2:2,\n",
        "}\n\n"
    ].

phase_declaration(Phases) ->
    [
        "enum Phase : u8 {\n",
        [
            [
                "  ", uppercase(Name), " = u8:", integer_to_list(Index),
                ",\n"
            ]
            || {Index, Name} <- lists:enumerate(0, Phases)
        ],
        "}\n\n"
    ].

machine_declarations(#{
    capacity := Capacity,
    output_names := OutputNames,
    data_name := DataName
}) ->
    DataStruct = record_struct_name(DataName),
    [
        "struct EntryEffects {\n",
        [
            [
                "  ", name(Port), "_valid: u1,\n",
                "  ", name(Port), ": axis::Frame,\n"
            ]
            || Port <- OutputNames
        ],
        "}\n\n",
        "struct MailboxSlot {\n",
        "  postponed: u1,\n",
        "  blocked_phase: Phase,\n",
        "  frame: axis::Frame,\n",
        "}\n\n",
        "struct Machine {\n",
        "  phase: Phase,\n",
        "  entered_from: Phase,\n",
        "  data: ", DataStruct, ",\n",
        "  slots: MailboxSlot[", integer_to_list(Capacity), "],\n",
        "  occupied: u8,\n",
        "  enter_pending: u1,\n",
        "  // Reserves one queue slot for the frame being assembled.\n",
        "  admission_pending: u1,\n",
        "  // A failed service ignores input until reset.\n",
        "  failed: u1,\n",
        "}\n\n"
    ].

%%%
%%% Lowered callbacks
%%%

initial_machine(#{init := #{body := Body, result := Result}}) ->
    [
        "fn initial_machine() -> Machine {\n",
        Body,
        "  ", Result, "\n",
        "}\n\n"
    ].

enter_function(#{
    data_name := DataName,
    output_names := OutputNames,
    entries := Entries
}) ->
    DataStruct = record_struct_name(DataName),
    [
        "fn enter(old_phase: Phase, phase: Phase, data: ", DataStruct,
        ") -> (", DataStruct, ", EntryEffects) {\n",
        "  match phase {\n",
        [entry_arm(Entry, OutputNames) || Entry <- Entries],
        "  }\n",
        "}\n\n"
    ].

entry_arm(#{
    phase := Phase,
    data := #{body := DataBody, result := DataResult},
    outputs := OutputSpecs
}, OutputNames) ->
    [
        "    Phase::", uppercase(Phase), " => {\n",
        "      let entered_data = {\n",
        indent(DataBody, 8),
        "        ", DataResult, "\n",
        "      };\n",
        [entry_output_binding(Port, maps:get(Port, OutputSpecs))
            || Port <- OutputNames],
        "      (entered_data, EntryEffects {\n",
        [
            [
                "        ", name(Port), "_valid: u1:",
                bool_digit(maps:get(valid, maps:get(Port, OutputSpecs))),
                ",\n",
                "        ", name(Port), ": ", name(Port), ",\n"
            ]
            || Port <- OutputNames
        ],
        "      })\n",
        "    },\n"
    ].

entry_output_binding(Port, #{valid := false}) ->
    [
        "      let ", name(Port), " = zero!<axis::Frame>();\n"
    ];
entry_output_binding(Port, #{
    valid := true,
    body := Body,
    result := Result
}) ->
    [
        "      let ", name(Port), " = {\n",
        indent(Body, 8),
        "        ", Result, "\n",
        "      };\n"
    ].

dispatch_function(#{
    message_names := MessageNames,
    data_name := DataName,
    casts := Casts
}) ->
    DataStruct = record_struct_name(DataName),
    [
        "fn dispatch(frame: axis::Frame, phase: Phase, data: ", DataStruct,
        ") -> (Phase, ", DataStruct, ", Directive) {\n",
        "  match frame.header.op as Tag {\n",
        [dispatch_tag_arm(Name, Casts) || Name <- MessageNames],
        "    _ => (phase, data, Directive::FAIL),\n",
        "  }\n",
        "}\n\n"
    ].

dispatch_tag_arm(Tag, Casts) ->
    TagCasts = [Cast || Cast <- Casts, maps:get(tag, Cast) =:= Tag],
    [
        "    Tag::", uppercase(Tag), " => {\n",
        "      let message = ", record_function_name(Tag),
        "_from_bits(frame.payload);\n",
        "      match phase {\n",
        [dispatch_phase_arm(Cast) || Cast <- TagCasts],
        "        _ => (phase, data, Directive::FAIL),\n",
        "      }\n",
        "    },\n"
    ].

dispatch_phase_arm(#{
    phase := Phase,
    body := Body,
    result := Result
}) ->
    [
        "        Phase::", uppercase(Phase), " => {\n",
        indent(Body, 10),
        "          ", Result, "\n",
        "        },\n"
    ].

%%%
%%% Bounded scheduler
%%%

service(#{
    capacity := Capacity,
    message_names := MessageNames,
    message_words := MessageWords,
    output_names := OutputNames
}) ->
    #{
        eligible_bindings := EligibleBindings,
        found_expression := FoundExpression,
        selected_expression := SelectedExpression,
        compaction_bindings := CompactionBindings,
        compacted_array := CompactedArray,
        unblocked_array := UnblockedArray
    } = queue_expansion(Capacity),
    [
        "proc Service {\n",
        "  req_in: chan<axis::Frame> in;\n",
        [
            ["  ", name(Port), "_out: chan<axis::Frame> out;\n"]
            || Port <- OutputNames
        ],
        "  admission_out: chan<u1> out;\n\n",
        "  config(req_in: chan<axis::Frame> in,\n",
        [
            ["         ", name(Port), "_out: chan<axis::Frame> out,\n"]
            || Port <- OutputNames
        ],
        "         admission_out: chan<u1> out) {\n",
        "    (req_in, ",
        join_with(", ", [[name(Port), "_out"] || Port <- OutputNames]),
        ", admission_out)\n",
        "  }\n\n",
        "  init { initial_machine() }\n\n",
        "  next(machine: Machine) {\n",
        "    if machine.failed {\n",
        "      machine\n",
        "    } else if machine.enter_pending {\n",
        entry_scheduler(OutputNames),
        "    } else {\n",
        "      let (tok, frame, received) = recv_if_non_blocking(\n",
        "        join(), req_in, machine.admission_pending,\n",
        "        zero!<axis::Frame>());\n",
        "      let tag_ok = ",
        tag_ok_expression(MessageNames, MessageWords), ";\n",
        "      let accepted = received && tag_ok;\n",
        "      let invalid_input = received && !tag_ok;\n",
        "      let incoming_slot = MailboxSlot {\n",
        "        frame,\n",
        "        ..zero!<MailboxSlot>()\n",
        "      };\n",
        "      let admitted_slots = if accepted {\n",
        "        update(machine.slots, machine.occupied as u32, incoming_slot)\n",
        "      } else { machine.slots };\n",
        "      let admitted_occupied = machine.occupied + (accepted as u8);\n",
        EligibleBindings,
        "      let found = ", FoundExpression, ";\n",
        "      let selected = ", SelectedExpression, ";\n",
        "      let selected_frame = admitted_slots[selected as u32].frame;\n",
        "      let dispatchable = found && !invalid_input;\n",
        "      let (next_phase, next_data, directive) =\n",
        "        if dispatchable {\n",
        "          dispatch(selected_frame, machine.phase, machine.data)\n",
        "        } else {\n",
        "          (machine.phase, machine.data, Directive::CONSUME)\n",
        "        };\n",
        "      let effective = dispatchable;\n",
        "      let selected_slot = admitted_slots[selected as u32];\n",
        "      let postponed_slot = MailboxSlot {\n",
        "        postponed: u1:1,\n",
        "        blocked_phase: machine.phase,\n",
        "        ..selected_slot\n",
        "      };\n",
        "      let postponed_slots = update(\n",
        "        admitted_slots, selected as u32, postponed_slot);\n",
        CompactionBindings,
        "      let compacted_slots = ", CompactedArray, ";\n",
        "      let transition_slots = match directive {\n",
        "        Directive::CONSUME => compacted_slots,\n",
        "        Directive::POSTPONE => postponed_slots,\n",
        "        Directive::FAIL => admitted_slots,\n",
        "      };\n",
        "      let candidate_slots = if effective {\n",
        "        transition_slots\n",
        "      } else { admitted_slots };\n",
        "      let candidate_occupied = if effective &&\n",
        "          directive == Directive::CONSUME {\n",
        "        admitted_occupied - u8:1\n",
        "      } else { admitted_occupied };\n",
        "      let candidate_phase = if effective {\n",
        "        next_phase\n",
        "      } else { machine.phase };\n",
        "      let candidate_data = if effective {\n",
        "        next_data\n",
        "      } else { machine.data };\n",
        "      let phase_changed = candidate_phase != machine.phase;\n",
        "      let unblocked_slots = ", UnblockedArray, ";\n",
        "      let final_slots = if phase_changed {\n",
        "        unblocked_slots\n",
        "      } else { candidate_slots };\n",
        "      let failed = invalid_input ||\n",
        "        (effective && directive == Directive::FAIL);\n",
        "      let admission_pending =\n",
        "        machine.admission_pending && !received;\n",
        "      // Preserve occupied + admission_pending <= capacity.\n",
        "      let reserve = !failed && !received && !admission_pending &&\n",
        "        candidate_occupied < MAILBOX_CAPACITY;\n",
        "      let _admission_tok = send_if(\n",
        "        tok, admission_out, reserve, u1:1);\n",
        "      Machine {\n",
        "        phase: candidate_phase,\n",
        "        entered_from: if phase_changed {\n",
        "          machine.phase\n",
        "        } else { machine.entered_from },\n",
        "        data: candidate_data,\n",
        "        slots: final_slots,\n",
        "        occupied: candidate_occupied,\n",
        "        enter_pending: effective && phase_changed && !failed,\n",
        "        admission_pending: admission_pending || reserve,\n",
        "        failed,\n",
        "        ..machine\n",
        "      }\n",
        "    }\n",
        "  }\n",
        "}\n\n"
    ].

entry_scheduler(OutputNames) ->
    SendBindings = [
        [
            "      let ", name(Port), "_tok = send_if(\n",
            "        join(), ", name(Port), "_out, effects.",
            name(Port), "_valid, effects.", name(Port), ");\n"
        ]
        || Port <- OutputNames
    ],
    Tokens = [[name(Port), "_tok"] || Port <- OutputNames],
    [
        "      let (entered_data, effects) = enter(\n",
        "        machine.entered_from, machine.phase, machine.data);\n",
        SendBindings,
        "      let reserve = !machine.admission_pending &&\n",
        "        machine.occupied < MAILBOX_CAPACITY;\n",
        "      let admission_tok = send_if(\n",
        "        join(), admission_out, reserve, u1:1);\n",
        "      let _entry_tok = ", join_tokens(Tokens ++ ["admission_tok"]),
        ";\n",
        "      Machine {\n",
        "        data: entered_data,\n",
        "        enter_pending: u1:0,\n",
        "        admission_pending: machine.admission_pending || reserve,\n",
        "        ..machine\n",
        "      }\n"
    ].

tag_ok_expression(MessageNames, MessageWords) ->
    join_with(" || ", [
        [
            "(frame.header.op == (Tag::", uppercase(Name), " as u8) && ",
            "frame.header.payload_words == u8:",
            integer_to_list(maps:get(Name, MessageWords)), ")"
        ]
        || Name <- MessageNames
    ]).

queue_expansion(Capacity) ->
    Indexes = lists:seq(0, Capacity - 1),
    EligibleBindings = [eligible_binding(Index) || Index <- Indexes],
    FoundExpression = join_with(" || ", [
        ["eligible_", integer_to_list(Index)] || Index <- Indexes
    ]),
    SelectedExpression = lists:foldr(
        fun(Index, Else) ->
            [
                "if eligible_", integer_to_list(Index), " { u8:",
                integer_to_list(Index), " } else { ", Else, " }"
            ]
        end,
        "u8:0",
        Indexes
    ),
    CompactionBindings = [
        compaction_binding(Index, Capacity) || Index <- Indexes
    ],
    CompactedArray = [
        "[",
        join_with(", ", [
            ["compacted_", integer_to_list(Index)] || Index <- Indexes
        ]),
        "]"
    ],
    UnblockedArray = [
        "[",
        join_with(",\n        ", [
            [
                "MailboxSlot { postponed: u1:0, ..candidate_slots[",
                integer_to_list(Index), "] }"
            ]
            || Index <- Indexes
        ]),
        "]"
    ],
    #{
        eligible_bindings => EligibleBindings,
        found_expression => FoundExpression,
        selected_expression => SelectedExpression,
        compaction_bindings => CompactionBindings,
        compacted_array => CompactedArray,
        unblocked_array => UnblockedArray
    }.

eligible_binding(Index) ->
    [
        "      let eligible_", integer_to_list(Index), " = u8:",
        integer_to_list(Index), " < admitted_occupied &&\n",
        "        (!admitted_slots[", integer_to_list(Index),
        "].postponed || admitted_slots[", integer_to_list(Index),
        "].blocked_phase != machine.phase);\n"
    ].

compaction_binding(Index, Capacity) when Index + 1 < Capacity ->
    [
        "      let compacted_", integer_to_list(Index), " = if u8:",
        integer_to_list(Index), " < selected {\n",
        "        admitted_slots[", integer_to_list(Index), "]\n",
        "      } else if u8:", integer_to_list(Index + 1),
        " < admitted_occupied {\n",
        "        admitted_slots[", integer_to_list(Index + 1), "]\n",
        "      } else { zero!<MailboxSlot>() };\n"
    ];
compaction_binding(Index, _Capacity) ->
    [
        "      let compacted_", integer_to_list(Index),
        " = zero!<MailboxSlot>();\n"
    ].

%%%
%%% Top-level streams
%%%

top(#{output_names := OutputNames}) ->
    [
        "pub proc Top {\n",
        "  ext_recv: chan<axis::Beat> in;\n",
        [
            ["  ", name(Port), "_send: chan<axis::Beat> out;\n"]
            || Port <- OutputNames
        ],
        "\n  config(ext_recv: chan<axis::Beat> in,\n",
        [
            ["         ", name(Port), "_send: chan<axis::Beat> out,\n"]
            || Port <- lists:droplast(OutputNames)
        ],
        "         ", name(lists:last(OutputNames)),
        "_send: chan<axis::Beat> out) {\n",
        "    let (req_p, req_c) = chan<axis::Frame, u32:1>(\"req\");\n",
        "    let (admit_p, admit_c) = chan<u1, u32:1>(\"admit\");\n",
        [
            [
                "    let (", name(Port), "_p, ", name(Port),
                "_c) = chan<axis::Frame, u32:1>(\"", name(Port), "\");\n"
            ]
            || Port <- OutputNames
        ],
        "    spawn axis::ReservedRx(ext_recv, req_p, admit_c);\n",
        "    spawn Service(req_c, ",
        join_with(", ", [[name(Port), "_p"] || Port <- OutputNames]),
        ", admit_p);\n",
        [
            [
                "    spawn axis::Tx(", name(Port), "_c, ", name(Port),
                "_send);\n"
            ]
            || Port <- OutputNames
        ],
        "    (ext_recv, ",
        join_with(", ", [[name(Port), "_send"] || Port <- OutputNames]),
        ")\n",
        "  }\n\n",
        "  init { () }\n",
        "  next(state: ()) { state }\n",
        "}\n"
    ].

%%%
%%% Naming and iodata helpers
%%%

uppercase(Atom) ->
    string:uppercase(atom_to_list(Atom)).

name(Atom) ->
    atom_to_list(Atom).

record_struct_name(Atom) ->
    string:titlecase(record_function_name(Atom)).

record_function_name(Atom) ->
    lists:delete($_, atom_to_list(Atom)).

bool_digit(true) -> "1";
bool_digit(false) -> "0".

join_tokens([Token]) ->
    Token;
join_tokens([First, Second | Rest]) ->
    join_tokens([["join(", First, ", ", Second, ")"] | Rest]).

join_with(_Separator, []) ->
    [];
join_with(Separator, [First | Rest]) ->
    [First | [[Separator, Item] || Item <- Rest]].

indent(Data, Spaces) ->
    Prefix = lists:duplicate(Spaces, $\s),
    Lines = string:split(iolist_to_binary(Data), "\n", all),
    [[Prefix, Line, "\n"] || Line <- Lines, Line =/= <<>>].
