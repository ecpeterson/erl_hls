-spec parse_file(string()) -> [erl_parse:abstract_form()].
-doc "Helper routine for reading an entire .erl source file into memory.".
parse_file(Filename) ->
    {ok, Epp} = epp:open([{name, Filename}]),
    try
        {ok, epp:parse_file(Epp)}
    after
        epp:close(Epp),
        err
    end.
