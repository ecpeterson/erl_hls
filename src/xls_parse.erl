-spec branch_from_clause(
    erl_parse:af_clause(),
    [atom()],
    atom(),
    fun((printable()) -> printable())
) -> {printable(), string()}.
-doc "Processes an Erlang clause from handle_*/2 into XLS.".
branch_from_clause(Clause, ArgVals, StateName, Postprocessor) ->
    Failure = [
        "let s = zero!<State>();\n",
        "    (axis::pack(Tag::ERROR as u8, ERROR_MATCH_FAILURE), ",
        "(Tag::STATE, s))"
    ],
    branch_from_clause(
        Clause,
        ArgVals,
        StateName,
        Postprocessor,
        Failure,
        #{}
    ).

branch_from_clause(
    Clause,
    ArgVals,
    StateName,
    Postprocessor,
    Failure,
    EnumAtoms
) ->
    {clause, _1, ArgPatterns, _2, Body} = Clause,
    InjectMatch = fun
        F({{match, LineNo, LHS, RHS}, Arg}) ->
            {match, LineNo, LHS, F({RHS, Arg})};
        F({X, Arg}) ->
            {match, element(2, X), X, Arg}
    end,
    BigBody = case ArgPatterns of
        [{nil, _L}] -> Body;
        _ -> lists:map(InjectMatch, lists:zip(ArgPatterns, ArgVals)) ++ Body
    end,
    ComputeState = lists:foldl(
        fun(Statement, State) ->
            statement_from_statement(Statement, State#clause_state{reference = none})
        end,
        #clause_state{state_name = StateName, enum_atoms = EnumAtoms}, BigBody
    ),

    OutState = instr(ComputeState, [
        "if (", mismatch_expression(
            ComputeState#clause_state.named_counters,
            #{}
        ), ") {\n",
        "    ", Failure, "\n",
        "} else {\n",
            %% TODO: it would be preferable to branch on the REPLY/NOREPLY tag,
            %% but we have to wait for the XLS type system to allow tagged sums,
            %% so that {reply, Reply, State} unifies with {noreply, State}.
        "    ", Postprocessor(reference(ComputeState)), "\n",
        "}"
    ]),

    {lists:reverse(OutState#clause_state.statements), OutState#clause_state.reference}.

-spec statement_from_statement(erl_parse:abstract_expression(), clause_state()) -> clause_state().
-doc """
Main transpiler workhorse.  Recursively converts a complex `erl_parse`
expression into a sequence of simple emitted XLS expressions.
""".
statement_from_statement(String, State) when is_list(String) ->
    reference(State, String);
statement_from_statement({atom, _L, true}, State) ->
    reference(State, "bool:1");
statement_from_statement({atom, _L, false}, State) ->
    reference(State, "bool:0");
statement_from_statement({atom, _L, Atom}, State = #clause_state{
    enum_atoms = EnumAtoms
}) ->
    reference(
        State,
        maps:get(Atom, EnumAtoms, string:uppercase(atom_to_list(Atom)))
    );
statement_from_statement({var, _L, Atom}, State) ->
    reference(State, get_name(State, Atom));
statement_from_statement({integer, _L, Integer}, State) ->
    reference(State, {static, integer, Integer});
statement_from_statement(X, State) when is_tuple(X) andalso op == element(1, X) ->
    [op, _L, Op | Args] = tuple_to_list(X),
    {BwdArgRefs, IntermediateState} = lists:foldl(
        fun(Arg, {ArgRefs, ThisState}) ->
            NewState = statement_from_statement(Arg, ThisState#clause_state{reference = none}),
            {[NewState#clause_state.reference | ArgRefs], NewState}
        end,
        {[], State}, Args
    ),
    instr(IntermediateState, op(Op, lists:reverse(BwdArgRefs)));
statement_from_statement({tuple, _L, Slots}, State) ->
    {BwdReferences, IntermediateState} = lists:foldl(
        fun(Slot, {References, ThisState}) ->
            NewState = statement_from_statement(Slot, ThisState#clause_state{reference = none}),
            {[NewState#clause_state.reference | References], NewState}
        end,
        {[], State}, Slots
    ),
    instr(IntermediateState, ["(", [[Ref, ", "] || Ref <- lists:reverse(BwdReferences)], ")"]);
statement_from_statement({record, _L, NameAtom, Fields}, State) ->
    {BwdAssignments, IntermediateState} = lists:foldl(
        fun({record_field, _1, {atom, _2, FieldAtom}, RHS}, {Assignments, ThisState}) ->
            NewState = statement_from_statement(RHS, ThisState#clause_state{reference = none}),
            {[{FieldAtom, NewState#clause_state.reference} | Assignments], NewState}
        end,
        {[], State}, Fields
    ),
    Assignments = lists:reverse(BwdAssignments),
    SecondState = instr(IntermediateState, [
        string:titlecase(lists:delete($_, atom_to_list(NameAtom))), " {\n",
        [["  ", atom_to_list(FieldAtom), ": ", Reference, ",\n"]
            || {FieldAtom, Reference} <- Assignments],
        "  ..zero!<", string:titlecase(lists:delete($_, atom_to_list(NameAtom))), ">()\n",
        "}"
    ]),
    instr(SecondState, record_value(NameAtom, reference(SecondState), SecondState));
statement_from_statement({record, _L, ToUpdate, NameAtom, UpdateFields}, State) ->
    InputState = statement_from_statement(ToUpdate, State),
    {BwdAssignments, IntermediateState} = lists:foldl(
        fun({record_field, _1, {atom, _2, FieldAtom}, RHS}, {Assignments, ThisState}) ->
            NewState = statement_from_statement(RHS, ThisState#clause_state{reference = none}),
            {[{FieldAtom, NewState#clause_state.reference} | Assignments], NewState}
        end,
        {[], InputState}, UpdateFields
    ),
    Assignments = lists:reverse(BwdAssignments),
    SecondState = instr(IntermediateState, [
        string:titlecase(lists:delete($_, atom_to_list(NameAtom))), " {\n",
            [["  ", atom_to_list(FieldAtom), ": ", Reference, ",\n"]
                || {FieldAtom, Reference} <- Assignments],
        "  ..(", InputState#clause_state.reference, ").1\n",
        "}"
    ]),
    instr(SecondState, record_value(NameAtom, reference(SecondState), SecondState));
statement_from_statement({'case', _L, Condition, Clauses}, State) ->
    lower_boolean_case(Condition, Clauses, State);
statement_from_statement({call, _L, MF, Args}, State) ->
    {remote, _1, {atom, _2, Module}, {atom, _3, FAtom}} = MF,

    {BwdArgRefs, ArgState} = lists:foldl(
        fun(Arg, {ArgRefs, ThisState}) ->
            NewState = statement_from_statement(Arg, ThisState#clause_state{reference = none}),
            {[NewState#clause_state.reference | ArgRefs], NewState}
        end,
        {[], State}, Args
    ),
    case Module:transpile(FAtom, lists:reverse(BwdArgRefs), ArgState) of
        X = #clause_state{} -> X;
        X -> instr(ArgState, X)
    end;
statement_from_statement({record_field, _L, Object, _RecordAtom, {atom, _LL, SlotAtom}}, State) ->
    IntermediateState = statement_from_statement(Object, State),
    instr(IntermediateState, [reference(IntermediateState), ".1.", atom_to_list(SlotAtom)]);
statement_from_statement({match, _L, LHS, RHS}, State) ->
    RHSState = statement_from_statement(RHS, State),
    destructure_lhs(LHS, RHSState).

%% XLS requires all branches of an expression to have one type.  This is the
%% directly representable subset of Erlang case: a boolean scrutinee, two
%% unguarded branches, and branch-local bindings whose final expressions have
%% the same XLS type.  This subset does not implement Erlang's rule for a
%% variable bound in every branch to become available after the case, so each
%% branch is emitted as its own lexical block.
lower_boolean_case(Condition, Clauses, State0) ->
    {TrueBody, FalseBody} = boolean_case_bodies(Clauses),
    ConditionState = statement_from_statement(
        Condition,
        State0#clause_state{reference = none}
    ),
    BranchBase = ConditionState#clause_state{
        statements = [],
        reference = none
    },
    TrueState = lower_expression_sequence(TrueBody, BranchBase),
    FalseState = lower_expression_sequence(FalseBody, BranchBase),
    AnonymousCounter = erlang:max(
        TrueState#clause_state.anonymous_counter,
        FalseState#clause_state.anonymous_counter
    ),
    CaseMatchCounter = erlang:max(
        TrueState#clause_state.match_counter,
        FalseState#clause_state.match_counter
    ) + 1,
    BaseCounters = BranchBase#clause_state.named_counters,
    MergedState = ConditionState#clause_state{
        anonymous_counter = AnonymousCounter,
        match_counter = CaseMatchCounter,
        reference = none
    },
    CaseState = instr(MergedState, [
        "if ", reference(ConditionState), " {\n",
        xls_parse_io:indent(print(
            lists:reverse(TrueState#clause_state.statements)
        ), 2),
        "  (", reference(TrueState), ", ", mismatch_expression(
            TrueState#clause_state.named_counters,
            BaseCounters
        ), ")\n",
        "} else {\n",
        xls_parse_io:indent(print(
            lists:reverse(FalseState#clause_state.statements)
        ), 2),
        "  (", reference(FalseState), ", ", mismatch_expression(
            FalseState#clause_state.named_counters,
            BaseCounters
        ), ")\n",
        "}"
    ]),
    CaseReference = reference(CaseState),
    MatchBase = "case_match_" ++ integer_to_list(CaseMatchCounter),
    {ExpectedName, ExpectedState} = uniquify(CaseState, MatchBase),
    {ActualName, ActualState} = uniquify(ExpectedState, MatchBase),
    ActualState#clause_state{
        reference = [CaseReference, ".0"],
        statements = [
            ["let ", ActualName, " = ", CaseReference, ".1;\n"],
            ["let ", ExpectedName, " = bool:false;\n"]
            | ActualState#clause_state.statements
        ]
    }.

boolean_case_bodies(Clauses) ->
    case lists:foldl(
        fun
            ({clause, _Line, [{atom, _PatternLine, true}], [], Body},
                    {none, False}) ->
                {Body, False};
            ({clause, Line, [{atom, _PatternLine, true}], [], _Body},
                    {_True, _False}) ->
                error({duplicate_xls_boolean_case_branch, Line, true});
            ({clause, _Line, [{atom, _PatternLine, false}], [], Body},
                    {True, none}) ->
                {True, Body};
            ({clause, Line, [{atom, _PatternLine, false}], [], _Body},
                    {_True, _False}) ->
                error({duplicate_xls_boolean_case_branch, Line, false});
            (Clause, _Bodies) ->
                error({unsupported_xls_case_clause, Clause})
        end,
        {none, none},
        Clauses
    ) of
        {none, _} -> error({missing_xls_boolean_case_branch, true});
        {_, none} -> error({missing_xls_boolean_case_branch, false});
        Bodies -> Bodies
    end.

lower_expression_sequence(Expressions, State0) ->
    lists:foldl(
        fun(Expression, State) ->
            statement_from_statement(
                Expression,
                State#clause_state{reference = none}
            )
        end,
        State0,
        Expressions
    ).

-spec mismatch_expression(map(), map()) -> printable().
mismatch_expression(Counters, Baseline) ->
    [
        [
            [
                "(", counter_name(Key), "_1 != ", counter_name(Key), "_",
                integer_to_list(Index), ") || "
            ]
            || Index <- rebound_indexes(
                maps:get(Key, Baseline, 0),
                Final
            )
        ]
        || Key := Final <- Counters
    ] ++ ["bool:false"].

rebound_indexes(Baseline, Final) ->
    First = erlang:max(2, Baseline + 1),
    case First =< Final of
        true -> lists:seq(First, Final);
        false -> []
    end.

counter_name(Key) when is_atom(Key) ->
    atom_to_list(Key);
counter_name(Key) ->
    Key.

-spec record_value(atom(), ir(), clause_state()) -> iolist().
record_value(NameAtom, Struct, #clause_state{state_name = NameAtom}) ->
    ["(Tag::", string:uppercase(atom_to_list(NameAtom)), ", ", Struct, ")"];
record_value(NameAtom, Struct, _State) ->
    [
        "(Tag::", string:uppercase(atom_to_list(NameAtom)), ", ", Struct, ", ",
        "bits_from_", lists:delete($_, atom_to_list(NameAtom)), "(", Struct, "))"
    ].

-spec destructure_lhs(erl_parse:af_pattern(), clause_state()) -> clause_state().
-doc """
Converts an assignment from an opaque RHS to a structured LHS into a sequence of
accessors into the RHS being assigned to slots inside of the LHS.
""".
destructure_lhs({var, _L, NameAtom}, State) ->
    %% TODO: need to record time-order data to report correct error
    %% TODO: also want to report eg line number on error, other present state
    {Name, NewState} = uniquify(State, NameAtom),
    RHS = NewState#clause_state.reference,
    Bind = ["let ", Name, " = ", RHS, ";\n"],
    NewState#clause_state{statements = [Bind | NewState#clause_state.statements]};
destructure_lhs({record, _L, _Atom, Slots}, State) ->
    RecordRef = State#clause_state.reference,
    IntermediateState = lists:foldl(
        fun({record_field, _1, {atom, _2, SlotAtom}, LHS}, ThisState) ->
            Slot = atom_to_list(SlotAtom),
            Substate = ThisState#clause_state{reference = [RecordRef, ".", Slot]},
            destructure_lhs(LHS, Substate)
        end,
        State, Slots
    ),
    IntermediateState#clause_state{reference = RecordRef};
destructure_lhs({tuple, _L, Slots}, State) ->
    TupleRef = State#clause_state.reference,
    IntermediateState = lists:foldl(
        fun({Index, LHS}, ThisState) ->
            Substate = ThisState#clause_state{
                reference = [TupleRef, ".", integer_to_list(Index)]
            },
            destructure_lhs(LHS, Substate)
        end,
        State,
        lists:enumerate(0, Slots)
    ),
    IntermediateState#clause_state{reference = TupleRef};
%% constant cases
destructure_lhs({atom, _L, Atom}, State) when Atom == true orelse Atom == false ->
    EncodedValue = case Atom of
        true -> "bool:1";
        false -> "bool:0"
    end,
    #clause_state{match_counter = OldMatchCounter} = State,
    MatchCounter = OldMatchCounter + 1,
    CounterState = State#clause_state{match_counter = MatchCounter},

    BaseName = "static_match_" ++ integer_to_list(MatchCounter),
    {StaticName, StaticState} = uniquify(CounterState, BaseName),
    {RHSName, RHSState} = uniquify(StaticState, BaseName),

    RHSValue = RHSState#clause_state.reference,

    RHSState#clause_state{
        reference = RHSName,
        statements = [
            ["let ", RHSName, " = ", RHSValue, " ;\n"],
            ["let ", StaticName, " = ", EncodedValue, " ;\n"]
            | CounterState#clause_state.statements
    ]}.
