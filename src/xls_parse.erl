-spec op_from_clause(erl_parse:af_clause()) -> atom().
-doc "Extracts the record type name being matched against in this Clause.".
op_from_clause(Clause) ->
    {clause, _1, [{record, _2, Atom, _Contents} | _Rest], _3, _Body} = Clause,
