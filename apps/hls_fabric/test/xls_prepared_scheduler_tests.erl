    ok
end}.

%% Common preparation acquires one interface inventory and normalizes one placement.
-spec prepare(direct | shared | mixed, hls_topology:plan(), file:filename(), hls_source:context()) ->
    {xls_fabric_topology_dslx:plan(), #{module() => xls_emitted:artifact()}, map()}.
prepare(Kind, Topology, Source, Context) ->
    {Generation, Calls} = trace_calls(fun() ->
        xls_fabric_topology_dslx:plan(Topology, profile(Kind))
    end, planning_targets()),
    assert_single_analysis(Calls),
    #{topology := Topology} = xls_fabric_topology_dslx:analysis(Generation),
    Requirements = xls_fabric_topology_dslx:artifact_requirements(Generation),
    ?assertEqual(requirements(Kind), Requirements),
    Artifact = xls_scheduler_actor:to_artifact(Source,
        (maps:get(hls_scheduler_build_fixture, Requirements))#{source_options => Context}),
    Artifacts = #{hls_scheduler_build_fixture => Artifact},
    Before = snapshot(Generation, Artifacts),
    Options = maps:with([mailbox_debug, direct_actor_debug, direct_collections, frame_payload_words], profile(Kind)),
    ?assertEqual(xls_scheduler_debug:projection(Topology, maps:get(scheduler_groups, profile(Kind)),
        Artifacts, Options), maps:get(projection, Before)),
    assert_ownership(Kind, Before),
    assert_routes(Kind, maps:get(descriptor, Before)),
    {Generation, Artifacts, Before}.

%% Consumer snapshots compare actual generated bytes as well as public planning facts.
-spec snapshot(xls_fabric_topology_dslx:plan(), #{module() => xls_emitted:artifact()}) -> map().
snapshot(Generation, Artifacts) ->
    Analysis = #{profile := #{frame_payload_words := Words}, scheduler := Scheduler,
        interfaces := Interfaces} = xls_fabric_topology_dslx:analysis(Generation),
    Bindings = xls_scheduler_ram_v:bindings(Scheduler, hls_frame_layout:new(Words), Interfaces),
    #{analysis => Analysis, descriptor => xls_fabric_topology_dslx:descriptor(Generation),
        requirements => xls_fabric_topology_dslx:artifact_requirements(Generation),
        dslx => iolist_to_binary(xls_fabric_topology_dslx:emit(Generation)),
        projection => xls_scheduler_debug:projection(Generation, Artifacts), bindings => Bindings,
        configurations => iolist_to_binary(xls_scheduler_ram_v:configurations(Bindings)),
        wires => iolist_to_binary(xls_scheduler_ram_v:wires(Bindings)),
        ports => iolist_to_binary(xls_scheduler_ram_v:application_ports(Bindings)),
        instances => iolist_to_binary(xls_scheduler_ram_v:instances(Bindings, "clk"))}.

%% Physical rows and observation identities must agree with the independently expected ownership.
-spec assert_ownership(direct | shared | mixed, map()) -> ok.
assert_ownership(Kind, #{analysis := #{scheduler := Scheduler}, descriptor := Descriptor,
        projection := #{<<"banks">> := Banks, <<"direct">> := Direct}, bindings := Bindings,
        configurations := Configurations, dslx := Dslx}) ->
    SharedFamilies = shared_families(Kind),
    ?assertEqual(representation(Kind), maps:get(representation, Descriptor)),
    ?assertEqual([{Family, Index, Y} || {Index, Family} <- lists:enumerate(0, SharedFamilies), Y <- [0, 1]],
        lists:sort([{Family, Index, Slot} || {{family, Family, [0, _]}, #{index := Index, slot := Slot}} <-
            maps:to_list(hls_scheduler_plan:placements(Scheduler))])),
    ?assertEqual(length(SharedFamilies), length(Bindings)),
    ?assertEqual(length(SharedFamilies), length(Banks)),
    lists:foreach(fun({#{index := Index, mailbox_width := MailboxWidth, state_width := StateWidth}, Bank}) ->
        ?assertEqual(64, MailboxWidth),
        ?assertEqual(Index, maps:get(<<"index">>, Bank)),
        ?assertEqual(StateWidth, maps:get(<<"width">>, Bank)),
        ?assertEqual(2, maps:get(<<"slots">>, Bank)),
        Family = lists:nth(Index + 1, SharedFamilies),
        ?assertEqual([{Y, hls_actor_identity:actor_key({family, Family, [0, Y]})} || Y <- [0, 1]],
            [{Slot, Key} || #{<<"slot">> := Slot, <<"key">> := Key} <- maps:get(<<"actors">>, Bank)]),
        Prefix = "scheduler_" ++ integer_to_list(Index),
        lists:foreach(fun(Store) ->
            ?assertNotEqual(nomatch, binary:match(Configurations,
                list_to_binary(Prefix ++ "_" ++ Store ++ ":1R1W:")))
        end, ["state", "mailbox"])
    end, lists:zip(Bindings, Banks)),
    [_Preamble, Top] = binary:split(Dslx, <<"pub proc Top {">>),
    [Declarations, _Config] = binary:split(Top, <<"  config(">>),
    lists:foreach(fun(Configuration) ->
        [_Name, <<"1R1W">> | Endpoints] = binary:split(Configuration, <<":">>, [global]),
        ?assertEqual(4, length(Endpoints)),
        %% XLS prefixes top-level channel endpoints with an underscore; DSLX declarations do not.
        lists:foreach(fun(<<"_", Name/binary>>) ->
            ?assertEqual(1, length(binary:matches(Declarations, <<"\n  ", Name/binary, ": chan<">>)))
        end, Endpoints)
    end, case Configurations of <<>> -> []; _ -> binary:split(Configurations, <<",">>, [global]) end),
    ExpectedDirect = [hls_actor_identity:actor_key({family, Family, [0, Y]}) ||
        Family <- [left, right] -- SharedFamilies, Y <- [0, 1]],
    ?assertEqual(lists:sort(ExpectedDirect), lists:sort([Key || #{<<"actors">> := Actors} <- Direct,
        #{<<"key">> := Key} <- Actors])),
    ?assertEqual(nomatch, binary:match(Dslx, <<"@@">>)),
    ok.

%% Compact shared routing keeps upstream ownership and startup order through preparation.
-spec assert_routes(direct | shared | mixed, xls_fabric_topology_dslx:descriptor()) -> ok.
assert_routes(shared, #{schedulers := [Left, Right], effect_window_domains := Domains}) ->
    ?assertEqual([[0, 1]], Domains),
    ?assertEqual([control, egress_credit], maps:get(producers, Left)),
    ?assertEqual([{scheduler, 0}, egress_credit], maps:get(producers, Right)),
    ?assertEqual([1], maps:get(destinations, Left)),
    ?assertEqual([], maps:get(destinations, Right)),
    lists:foreach(fun({Scheduler, Value}) ->
        ?assertEqual([#{slot => Y, schema => work, payload => <<(Value + Y):8, 0:24>>} || Y <- [0, 1]],
            maps:get(startup, Scheduler))
    end, [{Left, 7}, {Right, 9}]),
    ok;
assert_routes(_, _) -> ok.

%% Two two-member families exercise inter-family routing without a decoder workload.
-spec topology() -> hls_topology:plan().
topology() ->
    hls_topology:normalize(#{version => 1, actors => #{},
        families => #{left => #{module => hls_scheduler_build_fixture, shape => [1, 2]},
            right => #{module => hls_scheduler_build_fixture, shape => [1, 2]}},
        externals => [{monitor, out, [work]}], routes => [],
        ingresses => [{commands, {rectangle, [1, 2]}, [
            {all, [work], [{family, left, {embed, [1, 1], [0, 0]}}]}]}],
        route_relations => [{{left, out}, [{family, right, {translate, [0, 0], wrap}}]},
            {{right, out}, [{external, monitor}]}],
        startup => [{{Family, 0, Y}, [{work, Value + Y}]} || {Family, Value} <- [{left, 7}, {right, 9}], Y <- [0, 1]]}).

%% One selected ordinary-frame word applies to all placement alternatives.
-spec profile(direct | shared | mixed) -> xls_fabric_topology_dslx:profile().
profile(Kind) ->
    #{name => retained_scheduler, channel_depth => 1, actor_egress_depth => burst,
        scheduler_groups => maps:from_list([{Family, #{members => [{family, Family}],
            state_storage => block_ram, mailbox_storage => block_ram}} || Family <- shared_families(Kind)]),
        effect_window_partition => weak_components, frame_payload_words => 1,
        direct_actor_debug => true, mailbox_debug => Kind =/= direct}.

%% Placement changes observation requirements but not the actor's ordinary service.
-spec requirements(direct | shared | mixed) -> #{module() => map()}.
requirements(direct) -> #{hls_scheduler_build_fixture => #{shared_service => ordinary,
    frame_payload_words => 1, direct_actor_debug => true}};
requirements(shared) -> #{hls_scheduler_build_fixture => #{shared_service => ordinary,
    frame_payload_words => 1, mailbox_debug => true}};
requirements(mixed) -> #{hls_scheduler_build_fixture => #{shared_service => ordinary,
    frame_payload_words => 1, direct_actor_debug => true, mailbox_debug => true}}.

%% The first family alone is shared in the mixed case.
-spec shared_families(direct | shared | mixed) -> [left | right].
shared_families(direct) -> [];
shared_families(shared) -> [left, right];
shared_families(mixed) -> [left].

%% A partial family placement must choose the explicit instance representation.
-spec representation(direct | shared | mixed) -> compact_direct | compact_shared | materialized.
representation(direct) -> compact_direct;
representation(shared) -> compact_shared;
representation(mixed) -> materialized.

%% These two public analysis entries must run exactly once before consumers reuse their result.
-spec planning_targets() -> [{module(), atom(), arity()}].
planning_targets() -> [{hls_scheduler_plan, normalize, 4}, {hls_scheduler_plan, interfaces, 2}].

%% A live positive trace prevents a vacuous zero-reacquisition assertion later.
-spec assert_single_analysis(map()) -> ok.
assert_single_analysis(Calls) ->
    ?assertEqual(maps:from_list([{Target, 1} || Target <- planning_targets()]), Calls).

%% Retained generation must not rediscover source, compiler interfaces or physical graph ownership.
