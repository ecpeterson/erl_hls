%% Private OTP trace sessions observe only the caller and drain calls before each assertion.
-spec trace_calls(fun(() -> Result), [{module(), atom(), arity()}]) -> {Result, map()}.
trace_calls(Fun, Targets) ->
    lists:foreach(fun({Module, _, _}) -> {module, Module} = code:ensure_loaded(Module) end, Targets),
    {Collector, Monitor} = spawn_monitor(fun() -> collect(#{}) end),
    Session = trace:session_create(prepared_scheduler_calls, Collector, []),
    try
        1 = trace:process(Session, self(), true, [call]),
        lists:foreach(fun(Target) -> 1 = trace:function(Session, Target, [], []) end, Targets),
        Result = Fun(),
        1 = trace:process(Session, self(), false, [call]),
        Ref = trace:delivered(Session, self()),
        receive {trace_delivered, _, Ref} -> ok
        after 5000 -> error(scheduler_trace_delivery_timeout) end,
        Collector ! {collect, self(), Ref},
        receive {Ref, Counts} -> {Result, Counts}
        after 5000 -> error(scheduler_trace_collection_timeout) end
    after
        trace:session_destroy(Session), exit(Collector, kill),
        receive {'DOWN', Monitor, process, Collector, _} -> ok
        after 5000 -> error(scheduler_trace_cleanup_timeout) end
    end.

%% Keep call counts only; source forms and generated artifacts never enter trace diagnostics.
-spec collect(map()) -> ok.
collect(Counts) ->
    receive
        %% The traced caller entered a source acquisition or planning boundary.
        {trace, _, call, {Module, Function, Arguments}} ->
            Key = {Module, Function, length(Arguments)},
            collect(maps:update_with(Key, fun(N) -> N + 1 end, 1, Counts));
        %% The caller has crossed the session's trace delivery barrier.
        {collect, Owner, Ref} -> Owner ! {Ref, Counts}, ok
    end.

%% Preserve every source-removal fixture in a unique disposable directory.
-spec fresh(string()) -> file:filename().
fresh(Name) ->
    Root = filename:join(["_build", "prepared-scheduler-tests", Name ++ "-" ++
        integer_to_list(erlang:system_time(nanosecond)) ++ "-" ++
        integer_to_list(erlang:unique_integer([positive, monotonic]))]),
    ok = filelib:ensure_dir(filename:join(Root, "source.erl")), Root.
