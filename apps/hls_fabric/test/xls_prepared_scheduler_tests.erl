-module(xls_prepared_scheduler_tests).
-moduledoc "Small regressions for retained scheduler analysis and its generation, observation and RAM consumers; these are not hardware execution witnesses.".
-include_lib("eunit/include/eunit.hrl").

%% Direct, shared and mixed family placement all retain their checked source facts.
-spec retained_representations_test_() -> term().
retained_representations_test_() -> {timeout, 60, fun retained_representations/0}.

%% Removing source and includes must not change any retained consumer's result.
-spec retained_representations() -> ok.
retained_representations() ->
    Root = fresh("representations"),
    Source = filename:join(Root, "hls_scheduler_build_fixture.erl"),
    Header = filename:join(Root, "scheduler_value.hrl"),
    {ok, Original} = file:read_file("apps/hls_fabric/test/hls_scheduler_build_fixture.erl"),
    Typed = binary:replace(Original, <<"hls_nums:u8()">>, <<"?VALUE_TYPE">>, [global]),
    Included = binary:replace(Typed, <<"-module(hls_scheduler_build_fixture).">>,
        <<"-module(hls_scheduler_build_fixture).\n-include(\"scheduler_value.hrl\").">>),
    ok = file:write_file(Header, "-define(VALUE_TYPE, hls_nums:u8()).\n", [exclusive]),
    ok = file:write_file(Source, Included, [exclusive]),
    hls_scheduler_build_fixture = hls_build_sources:load(Source, []),
    try
        Topology = topology(),
        [Context] = proplists:get_value(hls_source_context,
            hls_scheduler_build_fixture:module_info(attributes)),
        Prepared = [prepare(Kind, Topology, Source, Context) || Kind <- [direct, shared, mixed]],
        ok = file:rename(Source, Source ++ ".retained"),
        ok = file:rename(Header, Header ++ ".retained"),
        {ok, Calls} = trace_calls(fun() ->
            lists:foreach(fun({Generation, Artifacts, Before}) ->
                ?assertEqual(Before, snapshot(Generation, Artifacts)),
                ?assertEqual(Before, snapshot(Generation, Artifacts))
            end, Prepared)
        end, retained_targets()),
        ?assertEqual(#{}, Calls),
        ok
    after
        hls_scheduler_build_fixture = hls_build_sources:load("apps/hls_fabric/test/hls_scheduler_build_fixture.erl", [])
    end.

%% The public source builder must reuse common planning for RAM and inspection too.
-spec public_build_analysis_once_test_() -> term().
public_build_analysis_once_test_() -> {timeout, 30, fun() ->
    Config = #{sources => [{"apps/hls_fabric/test/hls_scheduler_build_fixture.erl", []}],
        topology => {hls_scheduler_build_fixture, topology, []},
