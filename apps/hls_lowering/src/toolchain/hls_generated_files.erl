-module(hls_generated_files).
-moduledoc """
Generated-file composition shared by backend emitters and build frontends. Merges, prefixes and hashes in-memory relative file sets, then writes only at an explicit output boundary. Compiler-owned hls_artifact_bundle handles support snapshots and final external-tool manifests.
""".
%% In-memory file composition and identity.
-export([merge/1, prefix/2, hash/1]).

%% Explicit filesystem publication.
-export([write/2, write_into/2]).
%% Shared type contracts.
-export_type([files/0, output/0, output/1]).

-doc "Generated bytes keyed by nonempty relative paths without dot or empty components.".
-type files() :: #{string() => iodata()}.
-doc "Generated files and the builder's descriptor or other result, retained independently of output location.".
-type output() :: output(term()).

-doc "Generated bytes paired with a concrete builder result. Writers preserve Result without interpreting or widening its shape.".
-type output(Result) :: #{files := files(), result := Result}.

-doc "Combines file sets without overwriting a duplicate path, even when its bytes agree. Rejects invalid relative paths.".
-spec merge([files()]) -> files().
merge(Sets) ->
    lists:foldl(
        fun(Files, Acc) ->
            maps:fold(
                fun(Path, Bytes, Combined) ->
                    ok = relative(Path),
                    case maps:is_key(Path, Combined) of
                        true -> error({duplicate_generated_path, Path});
                        false -> Combined#{Path => Bytes}
                    end
                end,
                Acc,
                Files
            )
        end,
        #{},
        Sets
    ).

-doc "Places every file beneath one relative directory. Both directory and child paths must have nonempty, non-dot components.".
-spec prefix(string(), files()) -> files().
prefix(Directory, Files) ->
    ok = relative(Directory),
    maps:fold(
        fun(Path, Bytes, Acc) ->
            ok = relative(Path),
            Acc#{Directory ++ "/" ++ Path => Bytes}
        end,
        #{},
        Files
    ).

-doc "Hashes the exact generated bytes as lowercase hexadecimal SHA-256, independent of iodata segmentation.".
-spec hash(iodata()) -> binary().
hash(Bytes) -> binary:encode_hex(crypto:hash(sha256, Bytes), lowercase).

-doc "Validates all generated paths and bytes before creating a fresh output root, then writes exclusive files and returns result. Existing roots are rejected; later I/O failures retain partial output.".
-spec write(output(Result), file:filename()) -> Result.
write(#{files := Files, result := Result}, Directory) ->
    Entries = entries(Files),
    ok = filelib:ensure_dir(Directory),
    case file:make_dir(Directory) of
        ok -> ok;
        {error, eexist} -> error({generated_output_exists, Directory});
        {error, Reason} -> error({generated_output, Directory, Reason})
    end,
    ok = write_entries(Entries, Directory),
    Result.

-doc "Validates all paths and bytes, then adds exclusive files to a caller-owned output directory, creating needed parents. Existing files are never replaced; an I/O failure retains files already written. Returns result.".
-spec write_into(output(Result), file:filename()) -> Result.
write_into(#{files := Files, result := Result}, Directory) ->
    ok = write_entries(entries(Files), Directory),
    Result.

%% Validate the whole set before any filesystem operation; sorted paths make failures reproducible.
-spec entries(files()) -> [{string(), iodata()}].
entries(Files) ->
    Entries = lists:sort(maps:to_list(Files)),
    lists:foreach(
        fun({Path, Bytes}) ->
            ok = relative(Path),
            _ = iolist_size(Bytes)
        end,
        Entries
    ),
    Entries.

%% Parent creation is confined to the validated relative generated paths under the trusted root.
-spec write_entries([{string(), iodata()}], file:filename()) -> ok.
write_entries(Entries, Directory) ->
    lists:foreach(
        fun({Relative, Bytes}) ->
            Path = filename:join(Directory, Relative),
            ok = filelib:ensure_dir(Path),
            ok = file:write_file(Path, Bytes, [exclusive])
        end,
        Entries
    ).

%% Check raw separators before filename normalization could erase a dot component.
-spec relative(string()) -> ok.
relative(Path) ->
    Components = string:split(Path, "/", all),
    case
        filename:pathtype(Path) =:= relative andalso
            not lists:any(
                fun(Part) -> Part =:= [] orelse Part =:= "." orelse Part =:= ".." end, Components
            ) andalso
            not lists:member(0, Path)
    of
        true -> ok;
        false -> error({invalid_generated_path, Path})
    end.
